#!/usr/bin/env python3
"""
certify.py - proofs about every event a rule can see, not only the samples someone wrote.

A test shows that a rule fires on the events in its test file. certify reasons about ALL
events. It turns every rule into exact finite automata (tools/automata.py) over every
character a string can hold, then answers questions by exhaustive search over finite state
spaces. Every answer is either a proof or comes with a concrete event, and every concrete
event is replayed through tools/sigma_engine.py before it is reported.

What it checks on every build
  compile     every Sigma rule (the single-event rules and the correlation base rules) becomes
              a Boolean formula over atoms, each atom an automaton of one field that accepts
              exactly the values tools/sigma_engine.py accepts: case folding, wildcards, |re
              flags, anchors, missing and empty fields included. What cannot be modelled
              exactly is refused with the reason.
  fire        an event that fires the rule, built from the automata
  quiet       an event the rule stays quiet on, built the same way
  replay      both events go through the engine; a disagreement fails the run

The theory (regular languages, the constructions, why each answer is a proof) is in
docs/CERTIFY.md.

Usage
  rasd certify
  rasd certify --filter T1059 -v
  rasd certify my-rules/*.yml -v     # any Sigma rule file, not only the repository's
  rasd certify --json
  rasd certify --write        # refresh the generated part of docs/CERTIFY.md
  rasd certify --check        # CI: fail on a refusal, an engine disagreement or a stale page
"""
