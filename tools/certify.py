# --------------------------------------------------------------------------- #
# Atoms: one `field|modifiers: values` line, exactly as sigma_engine evaluates it
# --------------------------------------------------------------------------- #
@dataclass
class Test:
    """One value test, mirroring sigma_engine._match_single line by line."""
    text: str                       # how the test reads in a report
    when_missing: bool              # the verdict when the event lacks the field (or holds None)
    regex: fa.Regex | None          # the strings it accepts; None: exists / null, decided by emptiness
    nonempty: bool = False          # exists: true accepts every non-empty string; exists: false and null accept ""
    expected: Any = None            # the value as written in the rule, and the modifiers: what the engine is given
    mods: tuple[str, ...] = ()

    def dfa(self, ab: fa.Alphabet) -> fa.DFA:
        if self.regex is not None:
            return self.regex.dfa().lift(ab)
        return fa.DFA.empty_string(ab, accept_empty=not self.nonempty)


def make_test(name: str, mods: tuple[str, ...], expected: Any) -> Test:
    label = f"{name}{''.join('|' + m for m in mods)}: {expected!r}"
    if "exists" in mods:
        want = bool(expected)
        return Test(label, when_missing=not want, regex=None, nonempty=want, expected=expected, mods=mods)
    if expected is None:
        return Test(label, when_missing=True, regex=None, nonempty=False, expected=expected, mods=mods)
    e = str(expected)
    try:
        if "re" in mods:
            flags = sum(RE_FLAGS[m] for m in set(mods) & RE_FLAGS.keys())
            _regex(e, flags)                     # the engine's own error for an invalid pattern
            return Test(label, False, fa.compile_regex(e, flags, True, False), expected=expected, mods=mods)
        cased = "cased" in mods
        if not cased:
            e = e.lower()
        lowered = not cased
        if "contains" in mods:
            rx = fa.compile_regex(re.escape(e), 0, True, lowered)
        elif "startswith" in mods:
            rx = fa.compile_regex(re.escape(e) + "(?s:.*)", 0, False, lowered)
        elif "endswith" in mods:
            rx = fa.compile_regex("(?s:.*)" + re.escape(e), 0, False, lowered)
        elif "*" in e or "?" in e:
            rx = fa.compile_regex(_wildcard(e).pattern, re.DOTALL, False, lowered)
        else:
            rx = fa.compile_regex(re.escape(e), 0, False, lowered)
    except (SigmaError, fa.AutomataError) as err:
        raise CertifyError(f"{label}: {err}") from err
    return Test(label, False, rx, expected=expected, mods=mods)


class Atom:
    """A field's tests combined with OR, or with AND under |all, as sigma_engine._match_field does."""

    def __init__(self, key: str, expected: Any):
        try:
            name, mods = _parse_key(key)
            check_values(name, mods, expected)
        except SigmaError as e:
            raise CertifyError(str(e)) from e
        values = expected if isinstance(expected, list) else [expected]
        for v in values:
            if v is not None and not isinstance(v, (str, int, float, bool)):
                raise CertifyError(f"{key}: value {v!r} is not a scalar")
        self.key, self.name, self.field, self.mods = key, name, name.lower(), mods
        self.values = values
        self.all = "all" in mods
        self.tests = [make_test(name, mods, v) for v in values]
        self.when_missing = (all if self.all else any)(t.when_missing for t in self.tests)
        self.ident = (self.field, tuple(sorted(set(mods))), json.dumps(values, sort_keys=True, default=str))

    def alphabets(self) -> list[fa.Alphabet]:
        return [t.regex.dfa().alphabet for t in self.tests if t.regex is not None]

    def dfa(self, ab: fa.Alphabet) -> fa.DFA:
        if not self.tests:
            return fa.DFA.constant(ab, self.all)
        dfas = [t.dfa(ab) for t in self.tests]
        if len(dfas) == 1:
            return dfas[0]
        return fa.product(dfas, all if self.all else any)


# --------------------------------------------------------------------------- #
# Conditions: the engine's grammar, producing a formula instead of a verdict
# --------------------------------------------------------------------------- #
Node = tuple            # ("atom", i) | ("not", node) | ("and", [nodes]) | ("or", [nodes])
Term = frozenset        # a conjunction of literals (atom index, wanted truth)


class _ConditionParser:
    """sigma_engine._Parser's grammar (not > and > or, parentheses, 1 of / all of), building nodes."""

    def __init__(self, model: RuleModel, condition: str):
        try:
            self.t = tokenize(condition)
        except SigmaError as e:
            raise CertifyError(str(e)) from e
        self.i, self.model = 0, model

    def peek(self) -> str | None:
        return self.t[self.i].lower() if self.i < len(self.t) else None

    def take(self) -> str:
        if self.i >= len(self.t):
            raise CertifyError("Unexpected end of condition")
        self.i += 1
        return self.t[self.i - 1]

    def parse(self) -> Node:
        node = self.expr()
        if self.i != len(self.t):
            raise CertifyError(f"Unexpected token: {self.t[self.i]!r}")
        return node

    def expr(self) -> Node:
        parts = [self.term()]
        while self.peek() == "or":
            self.take()
            parts.append(self.term())
        return parts[0] if len(parts) == 1 else ("or", parts)

    def term(self) -> Node:
        parts = [self.factor()]
        while self.peek() == "and":
            self.take()
            parts.append(self.factor())
        return parts[0] if len(parts) == 1 else ("and", parts)

    def factor(self) -> Node:
        tok = self.peek()
        if tok is None:
            raise CertifyError("Unexpected end of condition")
        if tok == "not":
            self.take()
            return ("not", self.factor())
        if tok == "(":
            self.take()
            node = self.expr()
            if self.peek() != ")":
                raise CertifyError("Missing closing parenthesis")
            self.take()
            return node
        if tok in ("1", "all") and self.i + 1 < len(self.t) and self.t[self.i + 1].lower() == "of":
            quant = self.take().lower()
            self.take()
            try:
                names = resolve_pattern(self.model.detection, self.take())
            except SigmaError as e:
                raise CertifyError(str(e)) from e
            return ("and" if quant == "all" else "or", [self.model.selection(n) for n in names])
        name = self.take()
        if name not in self.model.detection or name in ("condition", "timeframe"):
            raise CertifyError(f"Condition references unknown selection '{name}'")
        return self.model.selection(name)


def evaluate(node: Node, truth: Sequence[bool]) -> bool:
    op = node[0]
    if op == "atom":
        return truth[node[1]]
    if op == "not":
        return not evaluate(node[1], truth)
    if op == "and":
        return all(evaluate(n, truth) for n in node[1])
    return any(evaluate(n, truth) for n in node[1])


def dnf(node: Node, positive: bool = True) -> list[Term]:
    """The formula (or its negation) as a list of conjunctions of literals, contradictions dropped
    and absorbed terms removed, smallest terms first."""
    op = node[0]
    if op == "atom":
        return [frozenset({(node[1], positive)})]
    if op == "not":
        return dnf(node[1], not positive)
    children = [dnf(n, positive) for n in node[1]]
    conjunctive = (op == "and") == positive
    if not conjunctive:
        terms = [t for c in children for t in c]
    else:
        terms = [frozenset()]
        for c in children:
            nxt = []
            for a in terms:
                for b in c:
                    t = a | b
                    if not any((i, not p) in t for i, p in t):
                        nxt.append(t)
            terms = _absorb(nxt)
            if len(terms) > DNF_LIMIT:
                raise CertifyError(f"the condition expands past {DNF_LIMIT} cases; refused")
    return _absorb(terms)


def _absorb(terms: list[Term]) -> list[Term]:
    out: list[Term] = []
    for t in sorted(set(terms), key=lambda t: (len(t), sorted(t))):
        if not any(o <= t for o in out):
            out.append(t)
    return out


# --------------------------------------------------------------------------- #
# A rule as a formula over field automata
# --------------------------------------------------------------------------- #
MISSING = None          # the value of a field the event does not carry


class RuleModel:
    """A Sigma rule as a Boolean formula over atoms; each atom is an exact automaton of one field."""

    def __init__(self, rule: dict, ident: str):
        self.rule, self.ident = rule, ident
        self.detection = rule.get("detection") or {}
        try:
            conds = conditions(self.detection)
        except SigmaError as e:
            raise CertifyError(str(e)) from e
        self.atoms: list[Atom] = []
        self._interned: dict[tuple, int] = {}
        self._selections: dict[str, Node] = {}
        parsed = [_ConditionParser(self, c).parse() for c in conds]
        self.formula: Node = parsed[0] if len(parsed) == 1 else ("or", parsed)
        self.fields: dict[str, list[int]] = {}
        self.names: dict[str, str] = {}
        for i, a in enumerate(self.atoms):
            self.fields.setdefault(a.field, []).append(i)
            self.names.setdefault(a.field, a.name)
        self._alphabet: dict[tuple, fa.Alphabet] = {}
        self._dfa: dict[tuple[int, int], fa.DFA] = {}

    # ---- translation --------------------------------------------------------
    def selection(self, name: str) -> Node:
        if name not in self._selections:
            sel = self.detection[name]
            if isinstance(sel, dict):
                node: Node = ("and", [self._atom(k, v) for k, v in sel.items()])
            elif isinstance(sel, list) and all(isinstance(s, dict) for s in sel):
                node = ("or", [("and", [self._atom(k, v) for k, v in s.items()]) for s in sel])
            elif isinstance(sel, list):
                raise CertifyError(f"selection '{name}' is a keyword list: it searches every field joined together, "
                                   "which depends on the whole event and is not modelled; write field conditions")
            else:
                raise CertifyError(f"Invalid selection type: {type(sel).__name__}")
            self._selections[name] = node
        return self._selections[name]

    def _atom(self, key: str, value: Any) -> Node:
        atom = Atom(key, value)
        if atom.ident not in self._interned:
            self._interned[atom.ident] = len(self.atoms)
            self.atoms.append(atom)
        return ("atom", self._interned[atom.ident])

    # ---- automata ------------------------------------------------------------
    def alphabet(self, field: str, extra: Sequence[fa.Alphabet] = ()) -> fa.Alphabet:
        """The classes of one field: every pattern the rule applies to it, and the alphabets of
        `extra` automata (a behaviour spec's patterns) that will be read on the same field."""
        key = (field, tuple(id(ab) for ab in extra))
        if key not in self._alphabet:
            abs_ = [ab for i in self.fields.get(field, []) for ab in self.atoms[i].alphabets()]
            self._alphabet[key] = fa.joint([*abs_, *extra])
        return self._alphabet[key]

    def atom_dfa(self, i: int, ab: fa.Alphabet) -> fa.DFA:
        key = (i, id(ab))
        if key not in self._dfa:
            self._dfa[key] = self.atoms[i].dfa(ab)
        return self._dfa[key]

    def verdict(self, event: dict) -> bool:
        """The rule's verdict computed from the automata alone (the engine is not consulted)."""
        truth = []
        for i, atom in enumerate(self.atoms):
            value = _get_field(event, atom.name)
            if isinstance(value, (list, dict)):
                raise CertifyError(f"field {atom.name!r} holds a {type(value).__name__}; certify models scalar fields")
            if value is None:
                truth.append(atom.when_missing)
            else:
                truth.append(self.atom_dfa(i, self.alphabet(atom.field)).run(str(value)))
        return evaluate(self.formula, truth)

    def size(self) -> dict:
        states = classes = 0
        for f, idx in self.fields.items():
            ab = self.alphabet(f)
            classes = max(classes, ab.size)
            states += sum(self.atom_dfa(i, ab).states for i in idx)
        return {"fields": len(self.fields), "atoms": len(self.atoms),
                "tests": sum(len(a.tests) for a in self.atoms), "states": states, "classes": classes}

    # ---- solving -------------------------------------------------------------
    def realize(self, term: Term) -> dict | None:
        """An event satisfying every literal of the term, or None when no event can. A field whose
        literals a missing field satisfies is left out, so the event carries only what the term needs."""
        by_field: dict[str, list[tuple[int, bool]]] = {}
        for i, want in term:
            by_field.setdefault(self.atoms[i].field, []).append((i, want))
        event: dict = {}
        for f, lits in sorted(by_field.items()):
            if all(self.atoms[i].when_missing == want for i, want in lits):
                continue
            ab = self.alphabet(f)
            word = fa.solve([(self.atom_dfa(i, ab), want) for i, want in sorted(lits)])
            if word is None:
                return None                     # neither a value nor a missing field satisfies this term
            event[self.names[f]] = ab.text(word)
        return event

    def check(self, event: dict, fires: bool) -> dict:
        """Replay a constructed event through the engine and through the automata."""
        if matches(self.rule, event) != fires or self.verdict(event) != fires:
            raise CertifyError(f"internal error: the engine disagrees with the automata on {event!r}")
        return event

    def witness(self, fires: bool) -> dict | None:
        """An event with the given verdict, checked by the engine; None proves that no event has it."""
        for term in dnf(self.formula, fires):
            event = self.realize(term)
            if event is not None:
                return self.check(event, fires)
        return None

    def near_miss(self, base: dict, fires: bool) -> tuple[int, dict] | None:
        """The event closest to `base` with the given verdict: the fewest character edits over its
        fields (a field added or removed costs its length plus one), checked by the engine."""
        best: tuple[int, dict] | None = None
        for term in dnf(self.formula, fires)[:TERM_LIMIT]:
            by_field: dict[str, list[tuple[int, bool]]] = {}
            for i, want in term:
                by_field.setdefault(self.atoms[i].field, []).append((i, want))
            cost, event = 0, dict(base)
            for f, lits in sorted(by_field.items()):
                key = next((k for k in base if k.lower() == f), self.names[f])
                current = None if base.get(key) is None else str(base[key])
                missing_ok = all(self.atoms[i].when_missing == want for i, want in lits)
                ab = self.alphabet(f)
                cons = [(self.atom_dfa(i, ab), want) for i, want in sorted(lits)]
                if current is None:
                    if missing_ok:
                        continue
                    word = fa.solve(cons)
                    if word is None:
                        break
                    event[key] = ab.text(word)
                    cost += len(word) + 1
                    continue
                found = fa.nearest(cons, current)
                if found is not None and (not missing_ok or found[0] <= len(current)):
                    cost += found[0]
                    event[key] = found[1]
                elif missing_ok:
                    cost += len(current) + 1
                    del event[key]
                else:
                    break
            else:
                if best is None or cost < best[0]:
                    best = (cost, event)
        return None if best is None else (best[0], self.check(best[1], fires))


# --------------------------------------------------------------------------- #
# Windows command lines: the arguments a program actually receives
# --------------------------------------------------------------------------- #
ARGV_SEP = "\x00"           # joins the arguments in an argv pattern; a command line never holds a NUL
_BLANK = fa.CharSet.points([0x09, 0x20])
_QUOTE = fa.CharSet.points([0x22])
_BACKSLASH = fa.CharSet.points([0x5C])
_NUL = fa.CharSet.points([0x00])
_OTHER = fa.CharSet.full() - (_BLANK | _QUOTE | _BACKSLASH | _NUL)


@functools.cache
def crt_transducer() -> fa.Transducer:
    """How the Microsoft C runtime splits a command line into the argv a program's wmain receives
    (Microsoft Learn, "Parsing C command-line arguments"), writing the arguments joined by NUL.

    argv[0] ends at the first space or tab outside quotes, and its quotes only group. Later
    arguments are separated by spaces and tabs; a quote opens or closes a quoted part, which can
    sit anywhere inside an argument (`d"e f"g` is `de fg`). Three readings are outside the model
    and rejected, because they need escapes or differ between runtime versions: a NUL, a
    backslash right before a quote, and two quotes in a row inside a quoted part."""
    a0, a0q, sep, arg, argq, arg_bs, argq_bs, closed = range(8)
    moves: dict[int, list[fa.Move]] = {
        a0: [(_OTHER | _BACKSLASH, a0, "", True), (_QUOTE, a0q, "", False), (_BLANK, sep, "", False)],
        a0q: [(_OTHER | _BACKSLASH | _BLANK, a0q, "", True), (_QUOTE, a0, "", False)],
        sep: [(_BLANK, sep, "", False), (_QUOTE, argq, ARGV_SEP, False), (_BACKSLASH, arg_bs, ARGV_SEP, True),
              (_OTHER, arg, ARGV_SEP, True)],
        arg: [(_BLANK, sep, "", False), (_QUOTE, argq, "", False), (_BACKSLASH, arg_bs, "", True), (_OTHER, arg, "", True)],
        argq: [(_QUOTE, closed, "", False), (_BACKSLASH, argq_bs, "", True), (_OTHER | _BLANK, argq, "", True)],
        arg_bs: [(_QUOTE, None, "", False), (_BACKSLASH, arg_bs, "", True), (_BLANK, sep, "", False), (_OTHER, arg, "", True)],
        argq_bs: [(_QUOTE, None, "", False), (_BACKSLASH, argq_bs, "", True), (_OTHER | _BLANK, argq, "", True)],
        closed: [(_QUOTE, None, "", False), (_BACKSLASH, arg_bs, "", True), (_BLANK, sep, "", False), (_OTHER, arg, "", True)],
    }
    return fa.Transducer(a0, range(8), moves)


def crt_argv(line: str) -> list[str] | None:
    """The same split, written directly as a parser (the reference the transducer is tested
    against): the program's argv, or None when the command line is outside the model."""
    if "\x00" in line:
        return None
    i, n, quoted, first = 0, len(line), False, []
    while i < n and (quoted or line[i] not in " \t"):
        if line[i] == '"':
            quoted = not quoted
        else:
            first.append(line[i])
        i += 1
    args = ["".join(first)]
    while True:
        while i < n and line[i] in " \t":
            i += 1
        if i >= n:
            return args
        cur: list[str] = []
        quoted = False
        while i < n and (quoted or line[i] not in " \t"):
            c = line[i]
            if c == "\\":
                j = i
                while j < n and line[j] == "\\":
                    j += 1
                if j < n and line[j] == '"':
                    return None
                cur.append(line[i:j])
                i = j
                continue
            if c == '"':
                if quoted and i + 1 < n and line[i + 1] == '"':
                    return None
                quoted = not quoted
            else:
                cur.append(c)
            i += 1
        args.append("".join(cur))


@functools.cache
def argv_dfa(pattern: str) -> fa.DFA:
    """The command lines whose argv, joined by NUL, the pattern matches in full."""
    try:
        return fa.preimage(crt_transducer(), fa.compile_regex(pattern, 0, False, False).dfa())
    except fa.AutomataError as e:
        raise CertifyError(f"argv pattern {pattern!r}: {e}") from e


# --------------------------------------------------------------------------- #
# Behaviour specs: every way a technique can appear in the events a rule reads
# --------------------------------------------------------------------------- #
SPEC = "behavior.yml"
EXPECTATIONS = ("fires", "bypass", "quiet")
BUILTINS = {"token": "[^\\x00]*"}            # one argument inside an argv pattern
_REF = re.compile(r"(?<!\\)((?:\\\\)*)\{([A-Za-z_][A-Za-z0-9_]*)\}")     # {name}, unless its brace is escaped
_ASCII_CI = re.compile(r"\{i:([^{}]*)\}")
_LOWER_EQ = re.compile(r"\{l:([^{}]*)\}")


def _ascii_ci(text: str) -> str:
    """A literal, with each ASCII letter in either case and nothing else widened: what a program that
    compares ASCII letters without case accepts."""
    return "".join(f"[{c.lower()}{c.upper()}]" if c.isascii() and c.isalpha() else re.escape(c) for c in text)


@functools.cache
def _same_lowercase() -> dict[str, str]:
    """For each character, every character whose str.lower() is the same single character."""
    groups: dict[str, set[str]] = {}
    multi = fa.multi_lower()
    for cp, low in enumerate(fa.lowered_text()):
        if cp not in multi and low != chr(cp):          # characters that lowercase to another character
            groups.setdefault(low, {low}).add(chr(cp))
    return {low: "".join(sorted(chars)) for low, chars in groups.items()}


def _lower_eq(text: str) -> str:
    """A literal as the engine's case-insensitive comparison reads it: every character whose
    lowercase equals the literal's (the Kelvin sign is a k), so an exclusion written with it is
    exactly as wide as the rule's."""
    same = _same_lowercase()
    out = []
    for c in text:
        chars = same.get(c.lower(), c)
        out.append(re.escape(c) if len(chars) == 1 else "[" + "".join(fa._escape(ord(x)) for x in chars) + "]")
    return "".join(out)


def expand(pattern: str, define: dict[str, str], where: str, depth: int = 0) -> str:
    """Replace {name} by its definition (in a group) and {i:text} by an ASCII case-insensitive literal."""
    if depth > 25:
        raise CertifyError(f"{where}: the definitions refer to each other in a loop")
    pattern = _ASCII_CI.sub(lambda m: _ascii_ci(m.group(1)), pattern)
    pattern = _LOWER_EQ.sub(lambda m: _lower_eq(m.group(1)), pattern)

    def sub(m: re.Match) -> str:
        slashes, name = m.group(1), m.group(2)
        if name in define:
            return slashes + "(?:" + expand(define[name], define, where, depth + 1) + ")"
        if name in BUILTINS:
            return slashes + "(?:" + BUILTINS[name] + ")"
        raise CertifyError(f"{where}: {{{name}}} is not defined")
    return _REF.sub(sub, pattern)


@dataclass(frozen=True)
class NumberSpec:
    """Numerals of integers: a prefix, then digits in a base, the value inside [0, max] with given
    bits set and clear. Bits of a number written in decimal depend on the whole numeral, yet the
    language is regular: reading digit d moves the remainder r to (r * base + d) mod 2^(k+1), and
    bit k is set exactly when that remainder is at least 2^k."""
    base: int = 10
    prefixes: tuple[str, ...] = ("",)
    bits_set: tuple[int, ...] = ()
    bits_clear: tuple[int, ...] = ()
    maximum: int | None = None
    leading_zeros: bool = False
    case: str = "any"                      # letters of base 16: any, lower or upper

    def digits(self) -> dict[str, int]:
        out = {str(d): d for d in range(min(self.base, 10))}
        for v in range(10, self.base):
            letter = "abcdef"[v - 10]
            if self.case in ("any", "lower"):
                out[letter] = v
            if self.case in ("any", "upper"):
                out[letter.upper()] = v
        return out

    def value(self, text: str) -> int | None:
        """The integer a numeral denotes under this spec, or None (read directly, for checking)."""
        digits = self.digits()
        for prefix in sorted(self.prefixes, key=len, reverse=True):
            rest = text[len(prefix):] if text.startswith(prefix) else None
            if not rest or any(c not in digits for c in rest):
                continue
            if not self.leading_zeros and len(rest) > 1 and rest[0] == "0":
                continue
            n = 0
            for c in rest:
                n = n * self.base + digits[c]
            if self.maximum is not None and n > self.maximum:
                continue
            if all(n >> b & 1 for b in self.bits_set) and not any(n >> b & 1 for b in self.bits_clear):
                return n
        return None

    def dfa(self) -> fa.DFA:
        return _number_dfa(self)

    def build(self) -> fa.DFA:
        digits = self.digits()
        modulus = 1 << (max([*self.bits_set, *self.bits_clear]) + 1) if self.bits_set or self.bits_clear else 1
        top = None if self.maximum is None else self._numeral(self.maximum)
        chars = sorted(set(digits) | {c for p in self.prefixes for c in p})
        ab = fa.Alphabet([fa.CharSet.points([ord(c)]) for c in chars])
        # a thread is ("pre", text read so far) or ("num", zero, length, order, remainder): zero - only
        # zeros read so far; length - significant digits; order - -1/0/1 against the maximum's digits.
        # A DFA state is the set of live threads (a prefix may be a prefix of another prefix).
        start_num = ("num", True, 0, 0, 0)

        def enter(text: str) -> set[tuple]:
            out: set[tuple] = set()
            if any(p.startswith(text) and p != text for p in self.prefixes):
                out.add(("pre", text))
            if text in self.prefixes:
                out.add(start_num)
            return out

        def step(th: tuple, c: str) -> set[tuple]:
            if th[0] == "pre":
                return enter(th[1] + c)
            if c not in digits:
                return set()
            _num, zero, length, order, rem = th
            d = digits[c]
            if zero and length > 0 and not self.leading_zeros:
                return set()                       # nothing may follow a leading 0
            rem = (rem * self.base + d) % modulus
            if zero and d == 0:
                return {("num", True, 1, 0, rem)}
            if zero:                               # the first significant digit
                length, order = 0, 0
            length += 1
            if top is not None:
                if length > len(top):
                    return set()
                if order == 0:
                    want = int(top[length - 1], 16)
                    order = -1 if d < want else 1 if d > want else 0
            return {("num", False, length, order, rem)}

        def accepts(th: tuple) -> bool:
            if th[0] == "pre":
                return False
            _num, zero, length, order, rem = th
            if length == 0:
                return False                       # a prefix with no digit after it
            if top is not None and not zero and length == len(top) and order > 0:
                return False
            return all(rem >> b & 1 for b in self.bits_set) and not any(rem >> b & 1 for b in self.bits_clear)

        first = frozenset(enter(""))
        index = {first: 0}
        order_ = [first]
        delta: list[list[int]] = []
        i = 0
        while i < len(order_):
            st = order_[i]
            i += 1
            row = []
            for k in range(ab.size):
                c = chr(ab.rep[k])
                nxt = frozenset(t for th in st for t in step(th, c)) if c in chars else frozenset()
                if nxt not in index:
                    index[nxt] = len(order_)
                    order_.append(nxt)
                row.append(index[nxt])
            delta.append(row)
        return fa.DFA(ab, delta, [any(accepts(th) for th in st) for st in order_]).minimize()

    def _numeral(self, n: int) -> str:
        out = ""
        while True:
            out = "0123456789abcdef"[n % self.base] + out
            n //= self.base
            if n == 0:
                return out


@functools.cache
def _number_dfa(spec: NumberSpec) -> fa.DFA:
    return spec.build()


def number_spec(raw: Any, where: str) -> NumberSpec:
    if not isinstance(raw, dict) or set(raw) - {"base", "prefix", "set", "clear", "max", "leading_zeros", "case"}:
        raise CertifyError(f"{where}: number takes base, prefix, set, clear, max, leading_zeros and case")
    base = int(raw.get("base", 10))
    if base not in (10, 16):
        raise CertifyError(f"{where}: number base must be 10 or 16")
    case = str(raw.get("case", "any"))
    if case not in ("any", "lower", "upper"):
        raise CertifyError(f"{where}: number case must be any, lower or upper")
    return NumberSpec(base, tuple(_listed(raw.get("prefix", ""))) or ("",),
                      tuple(int(b) for b in _listed(raw.get("set"))), tuple(int(b) for b in _listed(raw.get("clear"))),
                      None if raw.get("max") is None else int(raw["max"]), bool(raw.get("leading_zeros", False)), case)


@dataclass
class FieldSpec:
    """The values one field takes in a variant: every `match` pattern and none of the `not`
    patterns match in full, and the command line's argv matches `argv`; `missing` lets the event
    lack the field, and a field written as null must be missing."""
    name: str
    match: list[str]
    exclude: list[str]
    argv: str | None
    missing: bool
    must_be_missing: bool = False
    number: NumberSpec | None = None

    def automata(self) -> list[tuple[fa.DFA, bool]]:
        try:
            out = [(fa.compile_regex(p, 0, False, False).dfa(), True) for p in self.match]
            out += [(fa.compile_regex(p, 0, False, False).dfa(), False) for p in self.exclude]
        except fa.AutomataError as e:
            raise CertifyError(f"{self.name}: {e}") from e
        if self.argv is not None:
            out.append((argv_dfa(self.argv), True))
        if self.number is not None:
            out.append((self.number.dfa(), True))
        return out

    def alphabets(self) -> list[fa.Alphabet]:
        return [d.alphabet for d, _w in self.automata()]

    def constraints(self, ab: fa.Alphabet) -> list[tuple[fa.DFA, bool]]:
        return [(d.lift(ab), want) for d, want in self.automata()]

    def holds(self, value: Any) -> bool:
        """Membership checked with Python's re and the reference parser, not with the automata."""
        if value is None:
            return self.missing or self.must_be_missing
        if self.must_be_missing:
            return False
        v = str(value)
        if any(re.fullmatch(p, v) is None for p in self.match) or any(re.fullmatch(p, v) for p in self.exclude):
            return False
        if self.number is not None and self.number.value(v) is None:
            return False
        if self.argv is not None:
            args = crt_argv(v)
            return args is not None and re.fullmatch(self.argv, ARGV_SEP.join(args)) is not None
        return True


@dataclass
class Variant:
    name: str
    expect: str
    why: str
    reason: str
    fix: str
    sources: list[str]
    fields: dict[str, FieldSpec]             # by field name in lowercase
    examples: list[dict]
    counts: list[tuple[str, int]]            # (what, how many strings): exact sizes of finite pieces


@dataclass
class Spec:
    path: Path
    behaviour: str
    sources: dict[str, dict]
    variants: list[Variant]


def _listed(value: Any) -> list[str]:
    if value is None:
        return []
    return [str(v) for v in value] if isinstance(value, list) else [str(value)]


def load_spec(path: Path) -> Spec:
    """Read and check a behaviour spec; every mistake is a CertifyError naming the file and variant."""
    where = path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else str(path)
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        raise CertifyError(f"{where}: {e}") from e
    unknown = set(doc) - {"behaviour", "sources", "define", "variants"}
    if unknown:
        raise CertifyError(f"{where}: unknown keys {sorted(unknown)}")
    sources = {}
    for src in doc.get("sources") or []:
        if not isinstance(src, dict) or not {"id", "title", "url"} <= set(src):
            raise CertifyError(f"{where}: every source needs an id, a title and a url")
        sources[str(src["id"])] = src
    define = {str(k): str(v) for k, v in (doc.get("define") or {}).items()}
    variants = []
    for n, raw in enumerate(doc.get("variants") or [], 1):
        here = f"{where}: variant {n} ({raw.get('name', '?') if isinstance(raw, dict) else '?'})"
        if not isinstance(raw, dict) or not raw.get("name") or not raw.get("why") or not isinstance(raw.get("event"), dict):
            raise CertifyError(f"{here}: needs a name, a why and an event map")
        bad = set(raw) - {"name", "expect", "why", "reason", "fix", "sources", "event", "examples", "counts"}
        if bad:
            raise CertifyError(f"{here}: unknown keys {sorted(bad)}")
        expect = str(raw.get("expect", "fires"))
        if expect not in EXPECTATIONS:
            raise CertifyError(f"{here}: expect must be one of {', '.join(EXPECTATIONS)}")
        if expect != "fires" and not raw.get("reason"):
            raise CertifyError(f"{here}: an expected {expect} needs a reason")
        cited = _listed(raw.get("sources"))
        missing_src = [c for c in cited if c not in sources]
        if missing_src or not cited:
            raise CertifyError(f"{here}: cite at least one source from the spec's list (unknown: {missing_src})")
        fields: dict[str, FieldSpec] = {}
        for fname, fval in raw["event"].items():
            fwhere = f"{here}: field {fname}"
            if fval is None:
                fs = FieldSpec(str(fname), [], [], None, missing=True, must_be_missing=True)
            elif isinstance(fval, str):
                fs = FieldSpec(str(fname), [expand(fval, define, fwhere)], [], None, missing=False)
            elif isinstance(fval, dict):
                extra = set(fval) - {"match", "not", "argv", "missing", "number"}
                if extra:
                    raise CertifyError(f"{fwhere}: unknown keys {sorted(extra)}")
                argv = fval.get("argv")
                fs = FieldSpec(str(fname), [expand(p, define, fwhere) for p in _listed(fval.get("match"))],
                               [expand(p, define, fwhere) for p in _listed(fval.get("not"))],
                               None if argv is None else expand(str(argv), define, fwhere),
                               missing=bool(fval.get("missing", False)),
                               number=None if fval.get("number") is None else number_spec(fval["number"], fwhere))
            else:
                raise CertifyError(f"{fwhere}: write a pattern, a map (match / not / argv / number / missing) or null")
            for p in [*fs.match, *fs.exclude, *([fs.argv] if fs.argv else [])]:
                try:
                    re.compile(p)
                except re.error as e:
                    raise CertifyError(f"{fwhere}: invalid pattern: {e}") from e
            fs.automata()                      # refuses what cannot be modelled exactly
            if fname.lower() in fields:
                raise CertifyError(f"{fwhere}: the field appears twice")
            fields[fname.lower()] = fs
        examples = raw.get("examples") or []
        if not isinstance(examples, list) or not all(isinstance(e, dict) for e in examples):
            raise CertifyError(f"{here}: examples must be a list of events")
        counts = []
        for item in raw.get("counts") or []:
            if not isinstance(item, dict) or not item.get("what") or ("pattern" in item) == ("number" in item):
                raise CertifyError(f"{here}: each count needs what, and a pattern or a number")
            try:
                dfa = (fa.compile_regex(expand(str(item["pattern"]), define, here), 0, False, False).dfa()
                       if "pattern" in item else number_spec(item["number"], here).dfa())
            except fa.AutomataError as e:
                raise CertifyError(f"{here}: count {item['what']!r}: {e}") from e
            size = dfa.count_all()
            if size is None:
                raise CertifyError(f"{here}: count {item['what']!r} describes infinitely many strings")
            counts.append((str(item["what"]), size))
        variant = Variant(str(raw["name"]), expect, str(raw["why"]).strip(), str(raw.get("reason") or "").strip(),
                          str(raw.get("fix") or "").strip(), cited, fields, examples, counts)
        for k, ex in enumerate(examples, 1):
            for f, fs in fields.items():
                value = next((v for key, v in ex.items() if key.lower() == f), None)
                if not fs.holds(value):
                    raise CertifyError(f"{here}: example {k} is not in the variant (field {fs.name})")
        variants.append(variant)
    if not variants:
        raise CertifyError(f"{where}: no variants")
    if len({v.name for v in variants}) != len(variants):
        raise CertifyError(f"{where}: two variants share a name")
    return Spec(path, str(doc.get("behaviour") or "").strip(), sources, variants)


def _value(event: dict | None, field: str) -> Any:
    if not event:
        return None
    return next((v for k, v in event.items() if k.lower() == field), None)


class VariantCheck:
    """One variant against one rule: is there an event of the variant with the opposite verdict?"""

    def __init__(self, model: RuleModel, variant: Variant):
        self.model, self.v = model, variant
        self.fields = sorted(set(model.fields) | set(variant.fields))
        self.ab = {f: model.alphabet(f, variant.fields[f].alphabets() if f in variant.fields else [])
                   for f in self.fields}
        self.domain = {f: fs.constraints(self.ab[f]) for f, fs in variant.fields.items() if not fs.must_be_missing}
        for f, fs in variant.fields.items():
            if not fs.must_be_missing and not fs.missing and fa.solve(self.domain[f]) is None:
                raise CertifyError(f"variant '{variant.name}': no value of {fs.name} fits its patterns, "
                                   "so the variant describes no event")

    def name(self, f: str) -> str:
        return self.v.fields[f].name if f in self.v.fields else self.model.names[f]

    def realize(self, term: Term, base: dict | None) -> tuple[int, dict] | None:
        """The event of the variant closest to `base` (fewest edits) that satisfies the term."""
        by_field: dict[str, list[tuple[int, bool]]] = {}
        for i, want in term:
            by_field.setdefault(self.model.atoms[i].field, []).append((i, want))
        cost, event = 0, {}
        absent: set[str] = set()                         # fields the event must not carry
        for f in self.fields:
            lits, fs = sorted(by_field.get(f, [])), self.v.fields.get(f)
            missing_ok = (fs is None or fs.missing or fs.must_be_missing) and \
                all(self.model.atoms[i].when_missing == want for i, want in lits)
            if fs is not None and fs.must_be_missing:
                if not missing_ok:
                    return None
                absent.add(f)
                continue
            if fs is None and not lits:
                continue
            current = _value(base, f)
            cons = self.domain.get(f, []) + [(self.model.atom_dfa(i, self.ab[f]), want) for i, want in lits]
            options: list[tuple[int, str | None]] = []
            if missing_ok:
                options.append((0 if current is None else len(str(current)) + 1, None))
            word = fa.solve(cons)               # cheap: decides whether any value fits at all
            if word is not None:
                found = fa.nearest(cons, str(current)) if current is not None else None
                options.append(found if found is not None else (len(word) + 1, self.ab[f].text(word)))
            if not options:
                return None
            c, value = min(options, key=lambda o: (o[0], o[1] is None))
            cost += c
            if value is not None:
                event[self.name(f)] = value
            else:
                absent.add(f)
        for k, v in (base or {}).items():               # the example's other fields cannot change the verdict
            if not k.startswith("_") and k.lower() not in absent and all(k.lower() != e.lower() for e in event):
                event[k] = v
        return cost, event

    def counterexample(self) -> tuple[int, dict] | None:
        """None proves that every event of the variant gets the expected verdict; otherwise the
        counterexample closest to one of the variant's examples (or the shortest)."""
        want = self.v.expect == "quiet"         # a quiet variant is broken by an event that fires
        best: tuple[int, dict] | None = None
        bases: list[dict | None] = list(self.v.examples) or [None]
        for term in dnf(self.model.formula, want):
            for base in bases:
                found = self.realize(term, base)
                if found is not None and (best is None or found[0] < best[0]):
                    best = found
        if best is None:
            return None
        event = best[1]
        if matches(self.model.rule, event) != want or self.model.verdict(event) != want:
            raise CertifyError(f"internal error: the engine disagrees with the automata on {event!r}")
        for f, fs in self.v.fields.items():
            if not fs.holds(_value(event, f)):
                raise CertifyError(f"internal error: {event!r} is not in variant '{self.v.name}' (field {fs.name})")
        return best


def check_spec(model: RuleModel, spec: Spec) -> list[dict]:
    rows = []
    for v in spec.variants:
        row: dict = {"variant": v.name, "expect": v.expect, "why": v.why, "reason": v.reason, "fix": v.fix,
                     "sources": v.sources, "counts": v.counts}
        found = VariantCheck(model, v).counterexample()
        if found is None:
            row["result"] = "proven"
            for k, ex in enumerate(v.examples, 1):          # a proof and its own examples must agree
                if matches(model.rule, ex) != (v.expect != "quiet"):
                    raise CertifyError(f"internal error: variant '{v.name}' is proven but example {k} disagrees")
        else:
            row["result"] = "fires" if v.expect == "quiet" else "bypass"
            row["event"], row["edits"] = found[1], found[0] if v.examples else None
        row["ok"] = (row["result"] == "bypass") == (v.expect == "bypass")
        rows.append(row)
    return rows


def spec_problems(ident: str, rows: list[dict]) -> list[str]:
    out = []
    for r in rows:
        if r["ok"]:
            continue
        if r["expect"] == "fires":
            out.append(f"{ident}: variant '{r['variant']}': an event of it slips past the rule: "
                       f"{json.dumps(r['event'], ensure_ascii=False)} - fix the rule, or mark the variant "
                       "`expect: bypass` with a reason")
        elif r["expect"] == "bypass":
            out.append(f"{ident}: variant '{r['variant']}' is now caught for every value: change it to `expect: fires`")
        else:
            out.append(f"{ident}: variant '{r['variant']}' must stay quiet, but the rule fires on "
                       f"{json.dumps(r['event'], ensure_ascii=False)}")
    return out


