def rules(filter_: str | None = None) -> list[tuple[str, str, dict, Path | None]]:
    """(id, kind, rule, folder) for every Sigma rule: the single-event rules and the correlation base rules."""
    out: list[tuple[str, str, dict, Path | None]] = [(d.id, "rule", d.rule, d.folder) for d in load_detections(filter_)]
