def load_tests() -> list[dict]:
    tests = []
    for path in sorted(RED_DIR.glob("*/*/test.yml")):
        try:
            doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as e:
            doc = {"_yaml_error": " ".join(str(e).split())}
        doc["_folder"] = path.parent
        tests.append(doc)
    return tests


def technique_link(t: str) -> str:
    return f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)"


def rel(path: Path, start: Path) -> str:
    import os
    return os.path.relpath(path, start).replace(os.sep, "/")


def detections_of(test: dict) -> list[str]:
    out: list[str] = []
    for s in test.get("steps") or []:
        for d in s.get("detections") or []:
            if d not in out:
                out.append(d)
    return out


def correlations_of(test: dict) -> list[str]:
    out: list[str] = []
    for s in test.get("steps") or []:
        for d in s.get("correlations") or []:
            if d not in out:
                out.append(d)
    return out


def covers(test: dict) -> list[str]:
    """Everything the test must trigger: single-event detections, then correlations."""
    return detections_of(test) + correlations_of(test)


