def esc(value) -> str:
    """Prose from test.yml: <marker> and similar placeholders must show, not vanish as HTML tags."""
    text = " ".join(str(value).split()).replace("\\", "\\\\")          # a lone backslash escapes Markdown
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*", "\\*").replace("_", "\\_")


def bullets(items) -> str:
    return "\n".join(f"- {esc(i)}" for i in items)


def cell(value) -> str:
    """Prose inside a Markdown table cell: escaped, and pipes would split the cell."""
    return esc(value).replace("|", "\\|")


def code_cell(value) -> str:
    """A code span inside a table cell: literal text, only pipes need escaping."""
    return "`" + " ".join(str(value).split()).replace("|", "\\|") + "`"


def numbered(items) -> str:
    return "\n".join(f"{n}. {esc(i)}" for n, i in enumerate(items, 1))


def det_folder(det_id: str) -> Path:
    """detect/correlations/<id> for a correlation, detect/detections/<id> otherwise."""
    corr = CORRELATIONS / det_id
    return corr if corr.is_dir() else ROOT / "detect" / "detections" / det_id


def det_link(det_id: str, folder: Path) -> str:
    return f"[`{det_id}`]({rel(det_folder(det_id), folder)}/)"


def query_paths(det_id: str) -> tuple[Path, Path]:
    sub = ("correlations",) if (CORRELATIONS / det_id).is_dir() else ()
    return ROOT / "queries" / "kql" / Path(*sub) / f"{det_id}.kql", ROOT / "queries" / "spl" / Path(*sub) / f"{det_id}.spl"


def mapping_rows(test: dict) -> list[str]:
    m = test["mitre"]
    rows = []
    if m.get("technique"):
        rows.append(f"| **ATT&CK technique** | {technique_link(m['technique'])} {m.get('technique_name', '')} |")
    if m.get("related"):
        rows.append(f"| **Related** | {' · '.join(technique_link(t) for t in m['related'])} |")
    if m.get("tactics"):
        rows.append(f"| **Tactics** | {', '.join(m['tactics'])} |")
    for ext in m.get("other") or []:
        rows.append(f"| **{ext['framework']}** | {ext['id']} |")
    return rows


def render_readme(test: dict, playbook: str | None, scenario: str | None) -> str:
    folder: Path = test["_folder"]
    runner = RUNNERS[test["platform"]]
    dets = covers(test)
    status = "Detect: **covered**" if dets else ("Detect: **hunt only**" if test.get("gap", {}).get("hunt")
                                                   else "Detect: **gap**")
    if test.get("category") == "posture":
        status = "Posture check: **no detection expected**"
    lines = [f"# {esc(test['name'])}", "",
             "| | |", "|---|---|", *mapping_rows(test),
             f"| **Platform** | {test['platform'].replace('_', ' ')} · runner: {runner} |",
             f"| **Status** | {status} |",
             f"| **Requires** | {'administrator' if any(s.get('needs_admin') for s in test['steps']) else 'standard user'}"
             + (f" · opt-in `{', '.join(sorted({s['opt_in'] for s in test['steps'] if s.get('opt_in')}))}`"
                if any(s.get('opt_in') for s in test['steps']) else "") + " |",
             "", "## Objective", "", esc(test["objective"]), "",
             "## Prerequisites", "", bullets(test["prerequisites"]), "",
             "## Safety notes", "", bullets(test["safety"]), "",
             "## Execution", "", numbered(test["execution"]), "",
             "### Steps and the detections they must trigger", "",
             "| Step | Script | Needs | Expected detections |", "|---|---|---|---|"]
    for s in test["steps"]:
        needs = ", ".join(x for x in ["admin" if s.get("needs_admin") else "", f"`-{s['opt_in']}`" if s.get("opt_in") else "",
                                      ", ".join(f"`{p}`" for p in s.get("parameters") or [])] if x) or "-"
        expected = "<br>".join([det_link(d, folder) for d in s.get("detections") or []]
                               + [det_link(d, folder) + " (correlation)" for d in s.get("correlations") or []]) or (
                   "- (posture check)" if test.get("category") == "posture" else "gap")
        lines.append(f"| {cell(s['name'])} | [`{s['script']}`]({s['script']}) | {needs} | {expected} |")
    lines += ["", "## Links", "",
              "| | |", "|---|---|",
              "| Expected telemetry | [expected_telemetry.md](expected_telemetry.md) |",
              "| Detections | [detection_links.md](detection_links.md) |",
              "| DFIR artifacts | [dfir_artifacts.md](dfir_artifacts.md) |",
              "| Sample output | [sample_output.md](sample_output.md) |"]
    if playbook:
        lines.append(f"| DFIR playbook | [{Path(playbook).name}]({rel(ROOT / playbook, folder)}) |")
    if scenario:
        lines.append(f"| Purple scenario | [{Path(scenario).name}]({rel(ROOT / scenario, folder)}) |")
    cleanup = test["cleanup"]
    lines += ["", "## Cleanup", "", bullets(cleanup["actions"]), "",
              f"**Verification:** {esc(cleanup['verify'])}", ""]
    if (test.get("scripts") or {}).get("cleanup"):
        lines.append(f"Script: [`{test['scripts']['cleanup']}`]({test['scripts']['cleanup']}) "
                     "(exit code 0 only when the host is verified clean).")
    lines += ["", "## Run", "", "```" + ("powershell" if runner == "powershell" else "bash"), run_command(test), "```"]
    return "\n".join(lines) + "\n" + FOOTER


def run_command(test: dict) -> str:
    runner = RUNNERS[test["platform"]]
    if runner == "powershell":
        params, opt_ins = [], []
        for s in test["steps"]:
            if s.get("opt_in"):
                opt_ins.append(f"-{s['opt_in']}")
            for p in s.get("parameters") or []:
                params.append(f"-{p} <{p.lower()}>")
        params, opt_ins = list(dict.fromkeys(params)), list(dict.fromkeys(opt_ins))
        safe = f".\\red\\Invoke-RasdEmulation.ps1 -Test {test['id']} -LabConfirmed {' '.join(params)}".rstrip()
        if not opt_ins:
            return safe
        # the default run leaves the opt-in steps out; the second line adds them (restore the VM snapshot after it)
        return (safe + "    # default: opt-in steps skipped\n"
                + f"{safe} {' '.join(opt_ins)}    # adds the opt-in steps, on a VM you restore from a snapshot afterwards")
    flags = " ".join(f"--{p.lower()} <{p.lower()}>" for s in test["steps"] for p in s.get("parameters") or [])
    return f"python3 red/run_red.py --test {test['id']} --lab-confirmed {flags}".rstrip()


def render_telemetry(test: dict) -> str:
    if any(s.get("bind") for s in test["steps"]):
        key = (f"Search key: the objects this test creates carry the run marker (for example `{MARKER_EXAMPLE}`, plain or "
               "encoded as [detection links](detection_links.md) shows); its other events are bound to the run by host and time window.")
    else:
        key = ("None of this test's events carries the run marker: they are bound to the run by host and time window "
               "([detection links](detection_links.md)).")
    lines = [f"# Expected telemetry · {esc(test['name'])}", "", key, "",
             "| Source | Event | What it shows | Key fields | Used by |", "|---|---|---|---|---|"]
    folder = test["_folder"]
    for t in test["telemetry"]:
        fields = "<br>".join(f"{code_cell(k)}: {code_cell(v)}" for k, v in (t.get("fields") or {}).items()) or "-"
        used = "<br>".join(det_link(d, folder) for d in t.get("used_by") or []) or "investigation"
        lines.append(f"| {cell(t['source'])} | {cell(t['event'])} | {cell(t['description'])} | {fields} | {used} |")
    if test.get("logging"):
        lines += ["", "## Logging that must be enabled", "", bullets(test["logging"])]
    lines += ["", "If an event is missing, check it in this order: the audit policy or Sysmon configuration "
              "that writes it, the collector that forwards it, and the parser that maps its fields "
              "(`rasd doctor <export>` checks the last two)."]
    return "\n".join(lines) + "\n" + FOOTER


def render_detection_links(test: dict) -> str:
    folder = test["_folder"]
    lines = [f"# Detection links · {esc(test['name'])}", ""]
    dets = covers(test)
    if dets:
        lines += ["| Step | Detection | Rule | KQL | SPL | Evidence bound by |", "|---|---|---|---|---|---|"]
        for s in test["steps"]:
            for d in (s.get("detections") or []) + (s.get("correlations") or []):
                base = det_folder(d)
                is_corr = d in (s.get("correlations") or [])
                kql, spl = query_paths(d)
                tmpl = (s.get("bind") or {}).get(d)
                bound = (f"token {code_cell(tmpl)} (e.g. {code_cell(expand_token(str(tmpl), MARKER_EXAMPLE))})"
                         if tmpl else "host, time window" + (" and client address" if test["platform"] == "active_directory" else ""))
                rule = (f"[correlation.yml]({rel(base / 'correlation.yml', folder)}) · [base.yml]({rel(base / 'base.yml', folder)})"
                        if is_corr else f"[rule.yml]({rel(base / 'rule.yml', folder)})")
                lines.append(f"| {cell(s['name'])} | {det_link(d, folder)} | {rule} | "
                             f"[KQL]({rel(kql, folder)}) | [SPL]({rel(spl, folder)}) | {bound} |")
    gap = test.get("gap")
    if gap:
        lines += ["", "## Coverage gap", "", f"**Why there is no rule yet:** {esc(gap['reason'])}", "",
                  f"**Planned:** {esc(gap['planned'])}"]
        for h in gap.get("hunt") or []:
            lines.append(f"\n**Hunt available:** [{Path(h).name}]({rel(ROOT / h, folder)})")
    if test.get("category") == "posture":
        lines += ["", "This is a configuration check. It produces no attack telemetry worth alerting on; "
                  "its output is a findings list for the application owner."]
    if dets:
        sources = " ".join(str(t.get("source", "")) for t in test.get("telemetry") or [])
        logs = ["lab-export.jsonl"] + (["dc-export.jsonl"] if "domain controller" in sources else []) \
            + (["target-export.jsonl"] if "(target)" in sources else [])
        lines += ["", "Turn a lab run into evidence (the exports this test's events are logged in):", "", "```bash",
                  f"rasd evidence --results emulation-results.json --logs {' '.join(logs)}", "```"]
    return "\n".join(lines) + "\n" + FOOTER


def render_dfir(test: dict) -> str:
    lines = [f"# DFIR artifacts · {esc(test['name'])}", "",
             "| Artifact | Location | How to collect | Why it matters |", "|---|---|---|---|"]
    for a in test["dfir_artifacts"]:
        lines.append(f"| {cell(a['artifact'])} | {cell(a['location'])} | {code_cell(a['collect'])} | {cell(a['purpose'])} |")
    collect = (test.get("scripts") or {}).get("collect")
    if collect:
        lines += ["", f"[`{collect}`]({collect}) collects what it can of these before cleanup runs (see the script for "
                  "exactly which); the runner records the SHA-256 of every collected file in the results, so the evidence "
                  "can be verified later."]
    if (test.get("scripts") or {}).get("cleanup"):
        lines += ["", "Collect before cleaning up: the cleanup script removes what the test created, which can include "
                  "artifacts listed here ([cleanup](README.md#cleanup))."]
    else:
        lines += ["", "This test creates nothing to clean up; collect the artifacts while they are fresh."]
    return "\n".join(lines) + "\n" + FOOTER


def render_sample(test: dict, dets: dict, corrs: dict | None = None) -> str:
    s = test["sample_output"]
    lines = [f"# Sample output · {esc(test['name'])}", "",
             "Expected output, not a capture from a real host. The run marker is random on every run.", "",
             "## Console", "", "```text", s["console"].rstrip(), "```"]
    for ref in s.get("events") or []:
        det = dets[ref["detection"]]
        ev = next(e for e in det.tests("true_positive") if e.get("_case") == ref["case"])
        body = {k: v for k, v in ev.items() if k != "_case"}
        lines += ["", f"## Expected event → {ref['detection']}", "",
                  f"This is true positive *{ref['case']}* in "
                  f"[`tests/true_positive.jsonl`]({rel(det.folder / 'tests' / 'true_positive.jsonl', test['_folder'])}): "
                  "CI proves on every change that it matches the rule.", "",
                  "```json", json.dumps(body, indent=2, ensure_ascii=False), "```"]
    for ref in s.get("scenarios") or []:
        corr = (corrs or {})[ref["correlation"]]
        sc = next(x for x in corr.scenarios() if x["name"] == ref["scenario"])
        first_ev = dict(sc["events"][0])
        lines += ["", f"## Expected sequence → {ref['correlation']}", "",
                  f"Scenario *{ref['scenario']}* in "
                  f"[`tests/scenarios.yml`]({rel(corr.folder / 'tests' / 'scenarios.yml', test['_folder'])}): "
                  f"{len(sc['events'])} events from one source. CI proves on every change that the correlation fires "
                  "on it, and that the generated SPL and KQL return the same alert. First event of the sequence:", "",
                  "```json", json.dumps(first_ev, indent=2, ensure_ascii=False), "```"]
    for ex in s.get("illustrative_events") or []:
        lines += ["", f"## Illustrative event · {ex['title']}", "",
                  "Shape of the telemetry this test produces. No rule consumes it yet (see detection_links.md).", "",
                  "```json", json.dumps(ex["event"], indent=2, ensure_ascii=False), "```"]
    return "\n".join(lines) + "\n" + FOOTER


def machine_copy(test: dict) -> str:
    keep = {k: test[k] for k in ("id", "name", "platform") if k in test}
    keep["technique"] = (test.get("mitre") or {}).get("technique")
    keep["runner"] = RUNNERS[test["platform"]]
    keep["steps"] = [{**{k: s.get(k) for k in ("id", "name", "script", "detections", "needs_admin", "opt_in", "parameters")},
                      "correlations": s.get("correlations") or [], "bind": s.get("bind") or {}} for s in test["steps"]]
    scripts = test.get("scripts") or {}
    keep["scripts"] = {"cleanup": scripts.get("cleanup"), "collect": scripts.get("collect")}   # every key present:
    # the PowerShell runner uses Set-StrictMode, where reading a missing property throws
    return json.dumps(keep, indent=2, ensure_ascii=False) + "\n"


def links_for(test: dict) -> tuple[str | None, str | None]:
    """DFIR playbook and purple scenario declared by the test (paths relative to the repo root)."""
    return test.get("dfir_playbook"), test.get("purple_scenario")


def render_all(test: dict, dets: dict, corrs: dict | None = None) -> dict[str, str]:
    playbook, scenario = links_for(test)
    return {
        "README.md": render_readme(test, playbook, scenario),
        "expected_telemetry.md": render_telemetry(test),
        "detection_links.md": render_detection_links(test),
        "dfir_artifacts.md": render_dfir(test),
        "sample_output.md": render_sample(test, dets, corrs),
        "test.json": machine_copy(test),
    }


def render_catalog(tests: list[dict]) -> str:
    rows = ["| Test | Platform | ATT&CK | Detect | Runner |", "|---|---|---|---|---|"]
    for t in tests:
        dets = covers(t)
        state = ("covered" if dets else ("hunt only" if (t.get("gap") or {}).get("hunt") else
                 ("posture" if t.get("category") == "posture" else "gap")))
        tech = (t.get("mitre") or {}).get("technique")
        rows.append(f"| [{t['name']}]({rel(t['_folder'], RED_DIR)}/) | {t['platform'].replace('_', ' ')} | "
                    f"{technique_link(tech) if tech else '-'} | {state} | {RUNNERS[t['platform']]} |")
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate and fail on stale generated files")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    from correlation import load_correlations             # imported here: correlation imports replay
    tests = load_tests()
    dets = {d.id: d for d in load_detections()}
    corrs = {c.id: c for c in load_correlations()}

    if args.list:
        for t in tests:
            print(f"{t['platform']:<17} {t['id']:<32} {', '.join(covers(t)) or 'gap'}")
        return 0

    failing = 0
    for t in tests:
        errs = check_test(t, dets, corrs)
        label = f"{t.get('platform', '?')}/{t.get('id', t['_folder'].name)}"
        if errs:
            failing += 1
            print(f"{RED}[FAIL]{RESET} {label}")
            for e in errs:
                print(f"         - {e}")
            continue
        out = render_all(t, dets, corrs)
        stale = [name for name, body in out.items()
                 if not (t["_folder"] / name).exists() or (t["_folder"] / name).read_text(encoding="utf-8") != body]
        if args.check:
            if stale:
                failing += 1
                print(f"{RED}[STALE]{RESET} {label}: {', '.join(stale)} (run: rasd red)")
            else:
                print(f"{GREEN}[ OK ]{RESET} {label}")
        else:
            for name, body in out.items():
                (t["_folder"] / name).write_text(body, encoding="utf-8")
            print(f"{GREEN}[ OK ]{RESET} {label} {DIM}({len(out)} files){RESET}")

    readme = RED_DIR / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        if CATALOG_START in text and CATALOG_END in text:
            new = (text.split(CATALOG_START)[0] + CATALOG_START + "\n" + render_catalog(tests) + "\n" + CATALOG_END
                   + text.split(CATALOG_END)[1])
            if new != text:
                if args.check:
                    failing += 1
                    print(f"{RED}[STALE]{RESET} red/README.md catalog (run: rasd red)")
                else:
                    readme.write_text(new, encoding="utf-8")
    print(f"\n{BOLD}{len(tests)} offensive tests · {failing} problem(s){RESET}")
    return 1 if failing else 0


if __name__ == "__main__":
    sys.exit(main())
