def check_test(test: dict, dets: dict, corrs: dict | None = None) -> list[str]:
    if "_yaml_error" in test:
        return [f"test.yml is not valid YAML: {test['_yaml_error']}"]
    corrs = corrs or {}
    errs = []
    folder: Path = test["_folder"]
    for key in REQUIRED:
        if not test.get(key):
            errs.append(f"missing '{key}'")
    if test.get("id") != folder.name:
        errs.append("id must equal the folder name")
    if test.get("platform") != folder.parent.name or test.get("platform") not in PLATFORMS:
        errs.append(f"platform must be the parent folder and one of {PLATFORMS}")
    mitre = test.get("mitre") or {}
    techs = [mitre.get("technique")] + list(mitre.get("related") or [])
    if test.get("category") != "posture":
        for t in techs:
            if t and not re.fullmatch(r"T\d{4}(\.\d{3})?", str(t)):
                errs.append(f"invalid ATT&CK technique '{t}'")
        if not mitre.get("technique"):
            errs.append("mitre.technique is required (or set category: posture)")
        elif (name := TECHNIQUE_NAMES.get(str(mitre["technique"]))) is None:
            errs.append(f"mitre.technique {mitre['technique']} has no name in TECHNIQUE_NAMES (tools/common.py)")
        elif mitre.get("technique_name") != name:
            errs.append(f"mitre.technique_name must be the ATT&CK v{ATTACK_VERSION} name \"{name}\"")
    errs += [f"mitre.tactics: {t} is not an ATT&CK v{ATTACK_VERSION} tactic" for t in mitre.get("tactics") or []
             if t not in ATTACK_TACTICS]
    want = TECHNIQUE_TACTICS.get(str(mitre.get("technique")))
    if want and list(mitre.get("tactics") or []) != list(want):
        errs.append(f"mitre.tactics must be the tactics ATT&CK v{ATTACK_VERSION} lists for {mitre['technique']}, in matrix "
                    f"order: [{', '.join(want)}]")
    for s in test.get("steps") or []:
        for key in ("id", "name", "script"):
            if not s.get(key):
                errs.append(f"step missing '{key}'")
        if s.get("script") and not (folder / s["script"]).exists():
            errs.append(f"step script {s['script']} does not exist")
        for d in s.get("detections") or []:
            if d not in dets:
                errs.append(f"step {s.get('id')}: unknown detection '{d}'")
        for d in s.get("correlations") or []:
            if d not in corrs:
                errs.append(f"step {s.get('id')}: unknown correlation '{d}'")
        bind = s.get("bind") or {}
        if not isinstance(bind, dict):
            errs.append(f"step {s.get('id')}: bind must map detection id -> token template")
            bind = {}
        for d, tmpl in bind.items():
            if d not in (s.get("detections") or []):
                errs.append(f"step {s.get('id')}: bind names '{d}', which the step does not trigger")
            body = str(tmpl)
            for enc in TOKEN_ENCODINGS:
                body = body[len(enc):] if body.startswith(enc) else body
            if not any(f in body for f in TOKEN_FIELDS):
                errs.append(f"step {s.get('id')}: bind token for '{d}' must contain {{marker}} or {{hex}}")
    for key in ("cleanup", "collect"):
        script = (test.get("scripts") or {}).get(key)
        if script and not (folder / script).exists():
            errs.append(f"{key} script {script} does not exist")
    if not (test.get("scripts") or {}).get("cleanup"):
        errs.append("scripts.cleanup is required (it may verify that nothing persisted)")
    if not covers(test) and not test.get("gap") and test.get("category") != "posture":
        errs.append("no step triggers a detection: document the coverage gap under `gap`")
    if covers(test) and test.get("gap"):
        errs.append("a step triggers a detection, so the test has no coverage gap: remove `gap`")
    if test.get("gap") and not (test["gap"].get("reason") and test["gap"].get("planned")):
        errs.append("gap needs `reason` and `planned`")
    for i, t in enumerate(test.get("telemetry") or [], 1):
        for key in ("source", "event", "description"):
            if not t.get(key):
                errs.append(f"telemetry #{i}: missing '{key}'")
    for i, a in enumerate(test.get("dfir_artifacts") or [], 1):
        for key in ("artifact", "location", "collect", "purpose"):
            if not a.get(key):
                errs.append(f"dfir_artifacts #{i}: missing '{key}'")
    cleanup = test.get("cleanup") or {}
    if not cleanup.get("actions") or not cleanup.get("verify"):
        errs.append("cleanup needs `actions` and `verify`")
    sample = test.get("sample_output") or {}
    if not sample.get("console"):
        errs.append("sample_output.console is required")
    for ref in sample.get("events") or []:
        det = dets.get(ref.get("detection"))
        if not det:
            errs.append(f"sample event refers to unknown detection '{ref.get('detection')}'")
            continue
        ev = next((e for e in det.tests("true_positive") if e.get("_case") == ref.get("case")), None)
        if ev is None:
            errs.append(f"sample event '{ref.get('case')}' is not a true positive of {det.id}")
        elif not matches(det.rule, ev):
            errs.append(f"sample event '{ref.get('case')}' does not match {det.id}")
        else:
            tokens = [str(t) for t in ((s.get("bind") or {}).get(det.id) for s in test.get("steps") or []) if t]
            if tokens and not any(carries_token(ev, t, MARKER_EXAMPLE) for t in tokens):
                errs.append(f"sample event '{ref.get('case')}' carries none of the bind tokens "
                            f"{', '.join(expand_token(t, MARKER_EXAMPLE) for t in tokens)}: "
                            "evidence would reject the real event")
    if detections_of(test) and not sample.get("events"):
        errs.append("sample_output.events must reference the true positive that mirrors this test")
    for ref in sample.get("scenarios") or []:
        corr = corrs.get(ref.get("correlation"))
        if not corr:
            errs.append(f"sample scenario refers to unknown correlation '{ref.get('correlation')}'")
            continue
        sc = next((x for x in corr.scenarios() if x["name"] == ref.get("scenario")), None)
        if sc is None:
            errs.append(f"sample scenario '{ref.get('scenario')}' is not a scenario of {corr.id}")
        elif sc["expect"] != "fire" or not evaluate_correlation(corr, sc["events"]):
            errs.append(f"sample scenario '{ref.get('scenario')}' does not fire {corr.id}")
    missing = [c for c in correlations_of(test) if c not in {r.get("correlation") for r in sample.get("scenarios") or []}]
    if missing:
        errs.append(f"sample_output.scenarios must reference the scenario that mirrors this test for: {', '.join(missing)}")
    return errs


def evaluate_correlation(corr, events: list[dict]) -> list[dict]:
    from correlation import evaluate                     # imported here: correlation imports replay
    return evaluate(corr, events)


