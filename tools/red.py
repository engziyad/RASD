#!/usr/bin/env python3
"""
red.py - RASD-Red: one metadata file per offensive test, everything else generated.

Every offensive test lives in red/<platform>/<test>/ and is described once, in test.yml:
objective, ATT&CK mapping, steps and the detections (and correlations) each step must trigger, expected
telemetry, DFIR artifacts, cleanup, safety notes. red.py validates that file and renders
the documents the SOC, DFIR and purple team read, so they can never drift apart:

  README.md              objective, mapping, execution, safety, cleanup, links
  expected_telemetry.md  every event the test must produce, with the fields that matter
  detection_links.md     which detections each step must trigger (or the documented gap)
  dfir_artifacts.md      what to collect, where it lives, how to collect it, why
  sample_output.md       expected console output and the expected event, taken from the
                         detection's own true-positive tests (so the sample is test-backed)
  test.json              machine copy read by the PowerShell / Python runners

Checks (run by `rasd red --check` and in CI)
  - mandatory sections: objective, mapping, execution, telemetry, detection link or gap,
    DFIR artifacts, cleanup, safety, sample output
  - every script referenced exists; every detection and correlation referenced exists
  - every sample event exists in that detection's true positives AND matches the rule, and
    every sample scenario exists in that correlation's scenarios AND fires it: the
    Red -> Detect link is executed, not just written down
  - generated files are current (drift)

Usage
  rasd red              # render every test
  rasd red --check      # validate + fail on drift (CI)
  rasd red --list
"""
