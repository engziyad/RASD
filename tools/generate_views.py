#!/usr/bin/env python3
"""
generate_views.py - render role-based documentation from each detection's contract.

One source of truth (contract.yml + rule.yml + tests) -> many audiences:

  detect/detections/<id>/triage.md    SOC triage card for that alert
  detect/detections/<id>/response.md  IR evidence and containment for that alert
  detect/correlations/<id>/...        the same two cards for every correlation detection
  docs/views/SOC_L1.md            every triage card on one page
  docs/views/Incident_Response.md evidence and containment per detection
  docs/views/GRC_Audit.md         control evidence and stated limitations
  docs/views/Purple_Team.md       emulation, mutations and blind spots to attack next

Generated files are drift-checked in CI: edit contract.yml, never the output.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import CORRELATIONS, DETECTIONS  # noqa: E402
from validate import maturity_label  # noqa: E402
HEADER = "<!-- Generated by tools/generate_views.py from contract.yml - do not edit by hand. -->\n\n"
FOOTER = "\n---\n\n<sub>Generated by RASD · Attack-to-Defense Validation Framework</sub>\n"
CONDITIONS = yaml.safe_load((ROOT / "detect" / "risk_conditions.yml").read_text(encoding="utf-8"))["conditions"]


def count_lines(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for l in path.read_text(encoding="utf-8").splitlines() if l.strip())


def count_mutations(path: Path) -> int:
    if not path.exists():
        return 0
    return len((yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("mutations") or [])


def load() -> list[dict]:
    """Every detection, then every correlation (its correlation.yml stands in for rule.yml)."""
    items = []
    for kind, base, rule_file in (("detections", DETECTIONS, "rule.yml"), ("correlations", CORRELATIONS, "correlation.yml")):
        for folder in sorted(p for p in base.iterdir() if p.is_dir()) if base.exists() else []:
            rule = yaml.safe_load((folder / rule_file).read_text(encoding="utf-8"))
            contract = yaml.safe_load((folder / "contract.yml").read_text(encoding="utf-8"))
            tuning_path = folder / "tuning.yml"
            tuning = yaml.safe_load(tuning_path.read_text(encoding="utf-8")) if tuning_path.exists() else {}
            sub = "" if kind == "detections" else "correlations/"
            items.append({
                "folder": folder, "id": folder.name, "kind": kind, "rule": rule, "c": contract, "tuning": tuning or {},
                "tp": count_lines(folder / "tests" / "true_positive.jsonl"),
                "tn": count_lines(folder / "tests" / "true_negative.jsonl"),
                "mut": count_mutations(folder / "tests" / "mutations.yml"),
                "kql": f"../../queries/kql/{sub}{folder.name}.kql", "spl": f"../../queries/spl/{sub}{folder.name}.spl",
            })
    return items


def first_sentence(text: str) -> str:
    flat = " ".join(text.split())
    end = flat.find(". ")
    return flat if end == -1 else flat[: end + 1]


def bullets(items) -> str:
    return "\n".join(f"- {i}" for i in items)


def numbered(items) -> str:
    return "\n".join(f"{n}. {i}" for n, i in enumerate(items, 1))


def technique(d: dict) -> str:
    t = d["c"]["primary_technique"].split(".", 1)[1].upper()
    return f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)"


def risk_lines(c: dict) -> str:
    rm = c.get("risk_model") or {}
    if not rm:
        return "-"
    lines = [f"Base score **{rm.get('base_score')}**."]
    for kind, sign, key in (("increase_if", "+", "add"), ("decrease_if", "−", "subtract")):
        for item in rm.get(kind) or []:
            cond = CONDITIONS.get(item["condition"], {})
            how = "auto" if cond.get("resolve") == "auto" else "ask"
            lines.append(f"- {sign}{item[key]} if {item['condition'].replace('_', ' ')} "
                         f"*({how}: {cond.get('description', '').rstrip('.')})*")
    return "\n".join(lines)


def link(d: dict, link_prefix: str) -> str:
    """Link to the detection folder: a sibling (../) from its own cards, or from docs/views."""
    return f"{link_prefix}{d['id']}/" if link_prefix == "../" else f"{link_prefix}{d['kind']}/{d['id']}/"


def triage_card(d: dict, link_prefix: str = "") -> str:
    c, r = d["c"], d["rule"]
    dl = c["detection_logic"]
    benign = list(d["tuning"].get("noise_sources") or []) or list(r.get("falsepositives") or [])
    never = d["tuning"].get("never_tune") or []
    return f"""## {c['name']}

| | |
|---|---|
| **Technique** | {technique(d)} |
| **Severity** | `{r['level']}` · confidence `{dl['confidence']}` · expected noise `{dl['expected_noise']}` |
| **Rule** | [`{d['id']}`]({link(d, link_prefix)}){' · Sigma correlation' if d['kind'] == 'correlations' else ''} |

### What triggered
{first_sentence(r['description'])}

### L1 action
{c['response'].get('l1_action', '-')}

### First checks
{numbered(c['triage']['first_checks'])}

### Escalate if
{bullets(c['triage']['escalate_if'])}

### Risk
{risk_lines(c)}

### Known benign sources
{bullets(benign)}

### Never tune
{bullets(never) if never else '-'}
"""


def response_card(d: dict, link_prefix: str = "") -> str:
    c = d["c"]
    r = c["response"]
    return f"""## {c['name']}

**Technique:** {technique(d)} · **Rule:** [`{d['id']}`]({link(d, link_prefix)})

| Role | Action |
|---|---|
| SOC L2 | {r.get('l2_action', '-')} |
| Incident response | {r.get('ir_action', '-')} |

### Evidence to collect
{bullets(r['evidence'])}

### Containment
{numbered(r['containment'])}
"""


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + body.rstrip() + "\n" + FOOTER, encoding="utf-8")


def main() -> int:
    items = load()

    for d in items:
        write(d["folder"] / "triage.md", "# SOC Triage Card\n\n" + triage_card(d, "../"))
        write(d["folder"] / "response.md", "# Incident Response\n\n" + response_card(d, "../"))

    views = ROOT / "docs" / "views"
    prefix = "../../detect/"

    write(views / "SOC_L1.md",
          "# SOC L1 — Triage Cards\n\nOne card per detection: what fired, what to check first, "
          "and when to escalate.\n\n" + "\n---\n\n".join(triage_card(d, prefix) for d in items))

    write(views / "Incident_Response.md",
          "# Incident Response — Evidence & Containment\n\n"
          "Preserve evidence **before** containment actions that destroy it "
          "(deleting tasks, services or registry values).\n\n"
          + "\n---\n\n".join(response_card(d, prefix) for d in items))

    rows = ["| Detection | Technique | Maturity | Owner | TP / TN tests | Mutations | Coverage depth | SIEM queries |",
            "|---|---|---|---|---|---|---|---|"]
    limits = []
    for d in items:
        c = d["c"]
        rows.append(f"| [{c['name']}]({link(d, prefix)}) | {technique(d)} | {maturity_label(c['maturity'])} | {c['owner']} | "
                    f"{d['tp']} / {d['tn']} | {d['mut'] or '-'} | **{c['coverage_depth']['level']}** | "
                    f"[KQL]({d['kql']}) · [SPL]({d['spl']}) |")
        limits.append(f"### {c['name']}\n\n**Depth:** {c['coverage_depth']['level']} — "
                      f"{c['coverage_depth']['reason']}\n\n**Depends on:**\n"
                      f"{bullets(c['data_contract']['required_events'])}\n\n**Known blind spots:**\n"
                      f"{bullets(c['detection_logic']['blind_spots'])}\n")
    write(views / "GRC_Audit.md",
          "# GRC / Audit — Control Evidence\n\n"
          "Every row below is backed by artifacts in this repository and re-verified by CI on each change: "
          "the rule, its true-positive and true-negative tests, mutation tests where required, "
          "generated SIEM queries, the ATT&CK mapping and a response procedure.\n\n"
          "## Evidence register\n\n" + "\n".join(rows) +
          "\n\n## Stated limitations\n\nCoverage claims are only as strong as the telemetry they depend on. "
          "These limitations are part of the control statement, not footnotes.\n\n" + "\n".join(limits))

    red_by_det = {}
    for test in sorted((ROOT / "red").glob("*/*/test.yml")):
        doc = yaml.safe_load(test.read_text(encoding="utf-8")) or {}
        for step in doc.get("steps") or []:
            for det in (step.get("detections") or []) + (step.get("correlations") or []):
                red_by_det.setdefault(det, f"{test.parent.parent.name}/{test.parent.name}")
    prow = ["| Detection | Offensive test | Mutation cases | Depth | Attack next (blind spots) |", "|---|---|---|---|---|"]
    for d in items:
        c = d["c"]
        red = red_by_det.get(d["id"])
        emu = f"[{red.split('/')[-1]}](../../red/{red}/)" if red else "— manual"
        prow.append(f"| [{c['name']}]({link(d, prefix)}) | {emu} | {d['mut'] or '-'} | "
                    f"{c['coverage_depth']['level']} | {'<br>'.join(c['detection_logic']['blind_spots'])} |")
    write(views / "Purple_Team.md",
          "# Purple Team — Validation Backlog\n\n"
          "The blind spots column is the purple-team backlog: each item is a test to run, "
          "and each confirmed miss becomes a new detection or a documented accepted risk.\n\n"
          + "\n".join(prow) +
          "\n\nRun emulation: `.\\red\\Invoke-PurpleEmulation.ps1 -Technique <ID> -LabConfirmed`  \n"
          "Then: `python rasd.py evidence --results <results>/emulation-results.json --logs lab-export.jsonl`\n")

    write(views / "README.md",
          "# Role-Based Views\n\nGenerated from each detection's and each correlation's `contract.yml`.\n\n"
          "| View | Audience |\n|---|---|\n"
          "| [SOC_L1.md](SOC_L1.md) | Alert triage |\n"
          "| [Incident_Response.md](Incident_Response.md) | Evidence collection and containment |\n"
          "| [GRC_Audit.md](GRC_Audit.md) | Control evidence and limitations |\n"
          "| [Purple_Team.md](Purple_Team.md) | Emulation, mutations, blind-spot backlog |\n")

    corrs = sum(1 for d in items if d["kind"] == "correlations")
    print(f"[+] views generated for {len(items) - corrs} detections and {corrs} correlations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
