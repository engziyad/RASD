#!/usr/bin/env python3
"""
advise.py - RASD-Agent: the counsel. What to do next, computed from what the repository proves.

The agent reads what every other tool measured - the chain, the proofs, the certificates, the
near misses, the tunings, the backlog, the decoys, the public datasets - and turns it into
ranked findings, each with the evidence behind it and the exact next step. It is an adviser to
four people:

  analyst     what fires, what is blind, what is noisy, how an alert reads     (--for analyst)
  engineer    what is unproven, what gap has a fix, what rule comes next       (--for engineer)
  purple      which lab run validates most, which decoy to plant next          (--for purple)
  executive   how far RASD is proven, what it covers, what to fund next        (--for executive)

Nothing here is estimated. A finding exists because a tool measured it; its priority says how
far it is from a proof (now, next, planned, awareness); its id is stable across builds, so a
decision taken on it is remembered. The agent learns from three things, all recorded in the
repository where they can be read: the decisions people take on its findings (agent/decisions.yml:
accepted, rejected, deferred), what became of them (an accepted finding that disappears was
resolved), and your own telemetry (--logs: what is blind, noisy or one edit away in your
environment). A finding rejected twice in a family lowers the family's rank, and the page says so.

A language model is optional (tools/agent_model.py). With one, `--explain` adds a narrative,
`--propose` drafts rule edits and new rules, `--ask` answers a question; without one the same
commands run on the computed facts. Whatever a model writes passes the engine, the tests and the
proofs before it is kept, and nothing the agent writes reaches the repository except through a
proposal you apply and commit yourself: the agent never commits and never pushes.

Usage
  rasd advise                             # the counsel, every role
  rasd advise --for engineer              # one role (analyst, engineer, purple, executive)
  rasd advise --logs export.jsonl         # add what your own telemetry says (--profile auto, --learn)
  rasd advise --explain T1218 --tp 1      # why an alert fired and what to do, field by field
  rasd advise --explain T1218 --event alert.json [--share-events]
  rasd advise --propose <finding id>      # draft the change under agent/proposals/<id>/, verified
  rasd advise --apply <finding id>        # copy a proposal into the tree and run its gates
  rasd advise --decide <finding id> accept|reject|defer --note "..." [--until 2027-01-31] [--by name]
  rasd advise --ask "which rule should we write next and why?"
  rasd advise --json [file]               # the counsel as JSON
  rasd advise --write                     # regenerate agent/ADVICE.md (part of rasd build)
  rasd advise --check                     # CI: the page is current and the decisions file is valid
"""
