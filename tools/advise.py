    from chain import BACKLOG_TIERS, backlog_ranked, backlog_tier
    out = []
    for rank, (g, acts) in enumerate(backlog_ranked(repo), 1):
        tier = backlog_tier(g)
        groups = ", ".join(a["group"] for a in acts) or "no tracked group"
        name = f"{g['technique']} {g['name']}"
