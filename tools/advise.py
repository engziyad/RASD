def gate_rule(rule: dict, tps: list, tns: list) -> tuple[bool, str]:
    """The gates a drafted rule passes before it is written: it compiles, every true positive matches,
    every true negative stays quiet, both query backends convert it, the automata compile it."""
    from certify import CertifyError, RuleModel
    try:
        compile_rule(rule)
    except SigmaError as e:
        return False, f"the engine refuses the rule: {e}"
    if not isinstance(tps, list) or not isinstance(tns, list) or len(tps) < 4 or len(tns) < 4:
        return False, "fewer than 4 true positives or 4 true negatives"
    for i, ev in enumerate(tps, 1):
        if not isinstance(ev, dict) or _verdict(rule, ev) is not True:
            return False, f"true positive {i} does not match"
    for i, ev in enumerate(tns, 1):
        if not isinstance(ev, dict) or _verdict(rule, ev) is not False:
            return False, f"true negative {i} matches"
    for backend in ("kql", "spl"):
        try:
            convert(rule, backend)
        except SigmaError as e:
            return False, f"does not convert to {backend}: {e}"
    try:
        RuleModel(rule, rule.get("title", "draft"))
    except CertifyError as e:
        return False, f"the automata refuse it: {e}"
    return True, "accepted"


def draft_rule_edit(f: Finding, det: Detection, model: Model | None) -> tuple[dict[str, str], list[str]]:
    """Close a known behaviour gap: the witness event is kept as the true positive to add once the rule is
    widened; with a model, a candidate edit of the rule's detection block that the gates accepted - every
    existing test keeps its verdict, the gap's variant becomes proven, no other variant regresses, the rule
    mutation score does not fall, both backends convert."""
    from certify import certify_rule
    from prove import suite
    event = f.data.get("event")
    checks = [f"known gap '{f.data.get('variant')}' of {det.id}: {str(f.data.get('reason') or '').strip()}",
              f"fix recorded in the behaviour spec: {f.data.get('fix') or 'none; the spec documents the gap as accepted'}"]
    files: dict[str, str] = {}
    if isinstance(event, dict):
        files[f"agent/proposals/{slug(f.id)}/pending_true_positive.jsonl"] = json.dumps(
            {"_case": f"behaviour variant: {f.data.get('variant')}", **event}, ensure_ascii=False) + "\n"
        checks.append("the engine-confirmed event is written as pending_true_positive.jsonl: add it to tests/true_positive.jsonl once the rule catches it")
    if model is None:
        return files, checks
    before = certify_rule(det.id, "rule", det.rule, det.folder)
    tests = suite(det)
    old_score, _old_survivors = proof_with(det, det.rule)
    try:
        doc = model.json(
            "You are a detection engineer widening one Sigma rule so it also catches a documented variant without catching "
            "anything it is proven quiet on. Keys: detection (the complete new Sigma detection mapping, selections and condition), "
            "rationale (2 sentences). Keep every existing selection name. Change as little as possible.",
            json.dumps({"rule": {k: det.rule[k] for k in ("title", "logsource", "detection") if k in det.rule},
                        "variant": f.data.get("variant"), "why_it_is_missed": f.data.get("reason") or f.data.get("why"),
                        "fix_hint": f.data.get("fix"), "event_that_must_match": event,
                        "true_negatives_that_must_stay_quiet": det.tests("true_negative")[:8]},
                       ensure_ascii=False, default=str),
            ("detection", "rationale"), max_tokens=2500)
    except ModelError as e:
        checks.append(f"model edit unavailable: {e}")
        return files, checks
    cand = copy.deepcopy(det.rule)
    cand["detection"] = doc["detection"]
    try:
        spec_text = spec_closing(det, str(f.data.get("variant")))
    except ProposalError as e:
        checks.append(f"model edit not gated: {e}")
        return files, checks
    ok, why = gate_edit(det, cand, event, tests, before, old_score, spec_text)
    if not ok:
        checks.append(f"model edit ({model.describe()}) refused: {why}")
        return files, checks
    from certify import SPEC
    files[_rel(det.folder / "rule.yml")] = yaml.safe_dump(cand, sort_keys=False, allow_unicode=True, width=1000)
    files[_rel(det.folder / SPEC)] = spec_text
    if isinstance(event, dict):
        files[_rel(det.folder / "tests" / "true_positive.jsonl")] = _append_jsonl(
            det.folder, "true_positive", {"_case": f"behaviour variant: {f.data.get('variant')}", **event})
        files.pop(f"agent/proposals/{slug(f.id)}/pending_true_positive.jsonl", None)
        checks[:] = [c for c in checks if "pending_true_positive" not in c]
        checks.append("the engine-confirmed event joins tests/true_positive.jsonl")
    checks.append(f"model edit ({model.describe()}) accepted by the gates: {why}. Rationale: {' '.join(str(doc['rationale']).split())[:300]}")
    checks.append(f"the variant '{f.data.get('variant')}' now expects to fire in {SPEC}; rule.yml and {SPEC} are re-serialised, so review "
                  "their formatting in the diff")
    return files, checks


def proof_with(det: Detection, rule: dict, extra_tps: Sequence[dict] = (), extra_tns: Sequence[dict] = ()) -> tuple[float, list[str]]:
    """The rule mutation proof prove would compute for `rule` with the detection's tests plus the given ones,
    exactly as prove builds its suite (tests, technique and generic mutations, fuzzer variants, accepted
    mutants): the score and the descriptions of the surviving mutants."""
    import tempfile
    from prove import accepted, killed_by, mutants, suite
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp) / det.id
        shutil.copytree(det.folder / "tests", folder / "tests")
        for kind, extra in (("true_positive", extra_tps), ("true_negative", extra_tns)):
            if extra:
                path = folder / "tests" / f"{kind}.jsonl"
                text = path.read_text(encoding="utf-8").rstrip("\n") + "\n" if path.exists() else ""
                path.write_text(text + "".join(json.dumps(ev, ensure_ascii=False) + "\n" for ev in extra), encoding="utf-8")
        probe = Detection(folder, rule, det.contract)
        tests, accept = suite(probe), accepted(probe)
        total, survivors = 0, []
        for mid, _kind, desc, mrule, _meta in mutants(rule):
            if mid in accept:
                continue
            total += 1
            if killed_by(mrule, tests) is None:
                survivors.append(desc)
    return (100.0 if total == 0 else round(100 * (total - len(survivors)) / total, 1)), survivors


def spec_closing(det: Detection, variant: str) -> str:
    """behavior.yml with the variant's expectation turned from bypass to fires (its reason and fix removed), as
    the spec must read once the rule catches the variant; refused when the spec does not read back."""
    from certify import SPEC, CertifyError, load_spec
    import tempfile
    path = det.folder / SPEC
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    hit = [v for v in doc.get("variants") or [] if v.get("name") == variant]
    if len(hit) != 1:
        raise ProposalError(f"the behaviour spec has no single variant named '{variant}'")
    hit[0]["expect"] = "fires"
    hit[0].pop("reason", None)
    hit[0].pop("fix", None)
    text = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000)
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / SPEC).write_text(text, encoding="utf-8")
        try:
            load_spec(Path(tmp) / SPEC)
        except CertifyError as e:
            raise ProposalError(f"the spec no longer reads once the variant expects to fire: {e}") from e
    return text


def certify_with(det: Detection, rule: dict, spec_text: str | None) -> dict:
    """certify_rule on `rule` against the detection's behaviour spec, or against `spec_text` in its place."""
    import tempfile
    from certify import SPEC, certify_rule
    if spec_text is None:
        return certify_rule(det.id, "rule", rule, det.folder)
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp) / det.id
        folder.mkdir()
        (folder / SPEC).write_text(spec_text, encoding="utf-8")
        return certify_rule(det.id, "rule", rule, folder)


def gate_edit(det: Detection, cand: dict, event: dict | None, tests, before: dict, old_score: float,
              spec_text: str | None = None) -> tuple[bool, str]:
    """The gates a rule edit passes: the engine compiles it, every existing test keeps its verdict, the variant's
    event matches, both backends convert, the certificate holds with the spec as it must then read (every
    variant ok, every exclusion still proven, nothing proven before lost), and the rule mutation proof does
    not fall."""
    try:
        compile_rule(cand)
    except SigmaError as e:
        return False, f"the engine refuses the edit: {e}"
    for label, ev, exp in tests:
        if _verdict(cand, ev) != exp:
            return False, f"{label} changes verdict"
    if isinstance(event, dict) and _verdict(cand, event) is not True:
        return False, "the variant's event still does not match"
    for backend in ("kql", "spl"):
        try:
            convert(cand, backend)
        except SigmaError as e:
            return False, f"does not convert to {backend}: {e}"
    after = certify_with(det, cand, spec_text)
    if after.get("refused") or after.get("spec_error"):
        return False, f"the automata refuse it: {after.get('refused') or after.get('spec_error')}"
    old_rows = {v["variant"]: v for v in (before.get("behaviour") or {}).get("variants") or []}
    new_rows = {v["variant"]: v for v in (after.get("behaviour") or {}).get("variants") or []}
    for name, v in new_rows.items():
        o = old_rows.get(name)
        if not v["ok"]:
            return False, (f"exclusion '{name}' would fire" if v["expect"] == "quiet" else
                           f"variant '{name}' expects to {v['expect']} and the automata find an event that does not")
        if o and o["result"] == "proven" and v["result"] != "proven":
            return False, f"variant '{name}' was proven and is not any more"
    closed = sum(1 for n, v in new_rows.items() if v["expect"] == "fires" and v["result"] == "proven"
                 and old_rows.get(n, {}).get("result") == "bypass")
    new_score, survivors = proof_with(det, cand, [{"_case": "behaviour variant", **event}] if isinstance(event, dict) else [])
    if new_score < old_score:
        return False, f"rule mutation score falls from {old_score:.0f}% to {new_score:.0f}% (surviving: {'; '.join(survivors)})"
    return True, (f"{len(tests)} tests keep their verdicts, {_n(closed, 'gap variant')} now proven for every event, every "
                  f"exclusion still proven quiet, both backends convert, rule mutation score {new_score:.0f}%")


