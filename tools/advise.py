STOP = {"the", "and", "for", "with", "that", "this", "what", "which", "should", "would", "how", "why", "are", "our", "you",
        "does", "did", "can", "from", "into", "have", "has", "rasd", "about", "when", "where", "next", "them", "then", "than"}


def sections(paths: list[Path]) -> list[tuple[str, str, str]]:
    """(path, heading, text) for every heading section of the Markdown pages."""
    out = []
    for p in paths:
        text = p.read_text(encoding="utf-8")
        head, body = "", []   # type: str, list[str]
        for ln in text.split("\n"):
            if ln.startswith("#"):
                if body:
                    out.append((_rel(p), head, "\n".join(body).strip()))
                head, body = ln.strip("# ").strip(), []
            else:
                body.append(ln)
        if body:
            out.append((_rel(p), head, "\n".join(body).strip()))
    return [s for s in out if s[2]]


def _words(question: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9.]{3,}", question.lower()) if w not in STOP}


def retrieve(question: str, k: int = 3) -> list[tuple[str, str, str]]:
    """The page sections that answer a question best: keyword hits, weighted towards headings and short
    prose over long tables."""
    words = _words(question)
    paths = [*sorted((ROOT / "docs").glob("*.md")), ROOT / "README.md", *sorted((ROOT / "detect").glob("*/*/README.md")),
             *sorted((ROOT / "dfir" / "playbooks").glob("*.md")), ROOT / "deceive" / "README.md", ROOT / "red" / "README.md"]
    scored = []
    for path, head, body in sections([p for p in paths if p.exists()]):
        low = body.lower()
        hits = sum(low.count(w) for w in words) + 4 * sum(w in head.lower() for w in words)
        if hits:
            scored.append((hits / (1 + len(body) / 1500), path, head, body))
    scored.sort(key=lambda s: (-s[0], s[1], s[2]))
    return [(p, h, b) for _s, p, h, b in scored[:k]]


def relevant_findings(question: str, view: dict, k: int = 3) -> list[Finding]:
    """The open findings whose words overlap the question most."""
    words = _words(question)
    scored = []
    for f in view["ranked"]:
        text = f"{f.id} {f.title} {f.evidence} {f.action}".lower()
        hits = sum(text.count(w) for w in words)
        if hits:
            scored.append((-hits, f.priority, f.id, f))
    scored.sort(key=lambda s: s[:3])
    return [f for _h, _p, _i, f in scored[:k]]


def ask(question: str, repo, view: dict, model: Model | None) -> None:
    hits = retrieve(question)
    related = relevant_findings(question, view)
    print(f"{BOLD}Question{RESET} {question}\n")
    if related:
        print(f"{BOLD}From the counsel{RESET} {DIM}(computed; the ranked findings that speak to it){RESET}")
        for f in related:
            print(f"  {GOLD}●{RESET} {f.title}\n      {DIM}{f.evidence}{RESET}\n      → {f.action.splitlines()[0]}\n      {DIM}id: {f.id}{RESET}")
        print()
    if model is None:
        print(f"{BOLD}From the pages{RESET} {DIM}({model_status()}){RESET}\n")
        for path, head, body in hits:
            print(f"{GOLD}{path}{RESET} › {BOLD}{head}{RESET}\n{body[:900]}{'…' if len(body) > 900 else ''}\n")
        return
    system = ("You advise a security team on the RASD repository. Answer from the facts, findings and excerpts given and say when "
              "they do not cover the question; never invent counts, rules or results. Keys: answer (plain prose, at most 200 words), "
              "grounded_on (list of the excerpt paths and finding ids you used).")
    user = json.dumps({"question": question, "facts": facts_for_model(repo, view),
                       "findings": [{"id": f.id, "title": f.title, "evidence": f.evidence, "action": f.action} for f in related],
                       "excerpts": [{"path": p, "heading": h, "text": b[:1500]} for p, h, b in hits]}, ensure_ascii=False)
    try:
        doc = model.json(system, user, ("answer", "grounded_on"), max_tokens=700)
    except ModelError as e:
        print(f"{YELLOW}model unavailable: {e}{RESET}; the pages that answer it best:")
        for path, head, _b in hits:
            print(f"  {path} › {head}")
        return
    grounded = doc["grounded_on"] if isinstance(doc["grounded_on"], list) else [doc["grounded_on"]]
    print(f"{BOLD}Model answer{RESET} {DIM}({model.describe()}; prose, not verified - the counsel above is){RESET}\n{doc['answer']}\n"
          f"{DIM}grounded on: {', '.join(map(str, grounded))}{RESET}")


