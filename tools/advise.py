def decoy_chain(det_id: str) -> str | None:
    """For a deception rule: which decoys it watches, what lured the attacker to each, and where the lure
    leads next, so the analyst knows which alert to expect before and after this one."""
    doc = load_inventory()
    decoys = [d for d in doc.get("decoys") or [] if str(d.get("detection")) == det_id]
    if not decoys:
        return None
    by_id = {str(d.get("id")): d for d in doc.get("decoys") or []}
    lines = []
    for d in decoys:
        name = d.get("name") or d.get("path") or d.get("node_id")
        planted_in = [x for x in by_id.values() if str(d.get("id")) in (x.get("credentials_for") or [])]
        leads_to = [by_id[x] for x in (d.get("credentials_for") or []) if x in by_id]
        lure = " ".join(str(d.get("lure", "")).split())
        text = f"decoy {d.get('kind')} `{name}`: {lure}{'' if lure.endswith(('.', '!', '?')) else '.'}"
        if planted_in:
            text += " Before this alert, expect " + ", ".join(f"{x.get('detection')} on `{x.get('path') or x.get('name')}`" for x in planted_in) + "."
        if leads_to:
            text += " After it, expect " + ", ".join(f"{x.get('detection')} on `{x.get('name') or x.get('node_id')}`" for x in leads_to) + "."
        lines.append(text)
    return "\n  ".join(lines) + "\n  Whoever touched a decoy read a lure or enumerated the directory: treat the source as compromised until shown otherwise."


