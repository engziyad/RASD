def load_event(args, det) -> dict:
    if args.event:
        p = Path(args.event)
        if p.exists():
            doc = json.loads(p.read_text(encoding="utf-8").splitlines()[0]) if p.suffix == ".jsonl" else json.loads(p.read_text(encoding="utf-8"))
        else:
            doc = json.loads(args.event)
        return doc if isinstance(doc, dict) else doc[0]
    if args.tn:
        return det.tests("true_negative")[args.tn - 1]
    return det.tests("true_positive")[(args.tp or 1) - 1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--for", dest="role", choices=ROLES, help="one role's counsel")
    ap.add_argument("--logs", nargs="*", help="your own telemetry (JSONL exports): add what it says")
    ap.add_argument("--profile", help="telemetry profile the exports are written in (or 'auto')")
    ap.add_argument("--learn", action="store_true", help="with --logs: remember the environment's counts in agent/environment.yml")
    ap.add_argument("--noisy", type=float, default=NOISY_PER_DAY, help="alerts/day above which a rule is flagged noisy (default 20)")
    ap.add_argument("--explain", metavar="DETECTION", help="explain an alert of this detection")
    ap.add_argument("--event", help="the event: a JSON object, or a .json / .jsonl file (first record)")
    ap.add_argument("--tp", type=int, help="with --explain: the n-th true positive sample")
    ap.add_argument("--tn", type=int, help="with --explain: the n-th true negative sample")
    ap.add_argument("--share-events", action="store_true", help="share a redacted copy of the event with the model")
    ap.add_argument("--propose", metavar="FINDING", help="draft the change for a finding under agent/proposals/")
    ap.add_argument("--apply", metavar="FINDING", help="copy a proposal into the working tree and run its gates")
    ap.add_argument("--decide", nargs=2, metavar=("FINDING", "DECISION"), help="record accept, reject or defer")
    ap.add_argument("--note", help="with --decide: why")
    ap.add_argument("--until", help="with --decide defer: YYYY-MM-DD")
    ap.add_argument("--by", help="who decided (default: the USER / USERNAME environment variable)")
    ap.add_argument("--ask", metavar="QUESTION", help="a question, answered on the repository's facts and pages")
    ap.add_argument("--all", action="store_true", help="show set-aside and deferred findings in full")
    ap.add_argument("--json", nargs="?", const="-", metavar="FILE", help="the counsel as JSON (to stdout, or a file)")
    ap.add_argument("--write", action="store_true", help="regenerate agent/ADVICE.md")
    ap.add_argument("--check", action="store_true", help="CI: fail when agent/ADVICE.md is stale or decisions.yml is invalid")
    ap.add_argument("--model-status", action="store_true", help="say whether a model is configured")
    args = ap.parse_args()
    by = args.by or os.environ.get("USER") or os.environ.get("USERNAME")

    if args.model_status:
        print(model_status())
        return 0
    try:
        model = Model.from_env()
    except ModelError as e:
        print(f"{RED}{e}{RESET}")
        return 2
    if args.decide:
        fid, decision = args.decide
        decision = {"accept": "accepted", "reject": "rejected", "defer": "deferred"}.get(decision, decision)
        entry = record_decision(fid, decision, args.note, by, args.until)
        print(f"{GREEN}recorded{RESET} {json.dumps(entry, ensure_ascii=False)} in {_rel(DECISIONS)}; rasd advise --write refreshes the page")
        return 0
    if args.apply:
        return apply_proposal(args.apply, by)
    if args.explain:
        det = resolve_item(args.explain)
        explain_alert(det, load_event(args, det), model, args.share_events)
        return 0

    doc = load_decisions()
    errs = decision_errors(doc)
    if errs and (args.check or args.write):
        for err in errs:
            print(f"{RED}{err}{RESET}")
        return 1
    import chain
    repo = chain.Repo()
    findings = counsel(repo)
    today = dt.date.today()
    view = apply_decisions(findings, doc, today)

    if args.propose:
        f = next((x for x in findings if x.id == args.propose), None)
        if f is None:
            close = [x.id for x in findings if args.propose.lower() in x.id.lower()][:8]
            raise SystemExit(f"no current finding '{args.propose}'" + (f"; close: {', '.join(close)}" if close else ""))
        try:
            folder = propose(f, model)
        except ProposalError as e:
            print(f"{RED}not written: {e}{RESET}")
            return 1
        print(f"{GREEN}proposal written{RESET} {_rel(folder)}/  ({_rel(folder / 'PROPOSAL.md')})")
        print(f"  review it, then: rasd advise --apply {f.id}")
        return 0
    if args.ask:
        ask(args.ask, repo, view, model)
        return 0

    page = render_page(apply_decisions(findings, doc, None), repo_counts(repo))
    if args.check:
        if not ADVICE.exists() or ADVICE.read_text(encoding="utf-8") != page:
            print(f"{RED}{_rel(ADVICE)} is out of date (run: rasd advise --write){RESET}")
            return 1
        print(f"{GREEN}counsel current{RESET} · {len(view['ranked'])} open findings · {_rel(DECISIONS)} valid")
        return 0
    if args.write:
        AGENT.mkdir(exist_ok=True)
        ADVICE.write_text(page, encoding="utf-8")
        print(f"[+] {_rel(ADVICE)} · {len(view['ranked'])} open findings")
        return 0

    extra: dict = {}
    env_findings: list[Finding] = []
    if args.logs:
        logs = [Path(p) for p in args.logs]
        env_findings, summary = environment_counsel(logs, args.profile, args.noisy)
        extra["environment"] = summary
        if args.learn:
            print(f"[+] environment remembered in {_rel(learn_environment(summary, logs))}")
    if args.json:
        merged = apply_decisions([*findings, *env_findings], doc, today)
        text = json.dumps(as_json(merged, extra), indent=2, ensure_ascii=False, default=str) + "\n"
        if args.json == "-":
            print(text)
        else:
            Path(args.json).write_text(text, encoding="utf-8")
            print(f"[+] {args.json}")
        return 0
    counts = repo_counts(repo)
    print_console(view, args.role, f"RASD-Agent · counsel on the repository · {counts['detections']} detections, "
                                   f"{counts['techniques']} techniques, {counts['validated']} with lab evidence")
    if args.logs:
        env_view = apply_decisions(env_findings, doc, today)
        s = extra["environment"]
        print()
        print_console(env_view, args.role, f"Counsel on your telemetry · {s['events']} events ({s['profile']}) · {s['alerts']} alerts · "
                                           f"telemetry {s['telemetry']['ready']} ready, {s['telemetry']['degraded']} degraded, "
                                           f"{s['telemetry']['blind']} blind")
    if args.all and (view["set_aside"] or view["deferred"]):
        print(f"\n{BOLD}Set aside and deferred{RESET}")
        for x in [*view["set_aside"], *view["deferred"]]:
            d = x.decision or {}
            print(f"  {d.get('decision')} {x.id}: {x.title}\n      {DIM}{d.get('note', '')} {('until ' + str(d['until'])) if d.get('until') else ''}{RESET}")
    print(f"\n{DIM}{model_status()}{RESET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
