def write_proposal(f: Finding, files: dict[str, str], checks: list[str], origin: str) -> Path:
    folder = PROPOSALS / slug(f.id)
    if folder.exists():
        shutil.rmtree(folder)
    (folder / "files").mkdir(parents=True)
    for rel, text in files.items():
        own = f"agent/proposals/{slug(f.id)}/"           # a note of the proposal itself, not a file to apply
        target = folder / rel[len(own):] if rel.startswith(own) else folder / "files" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    listed = "\n".join(f"- `{rel}`" for rel in sorted(files)) or "- (no file: the next step is a procedure, listed below)"
    body = (f"# Proposal · {f.title}\n\n**Finding** `{f.id}` · priority {PRIORITY[f.priority]} · for {', '.join(f.roles)}\n\n"
            f"**Evidence.** {f.evidence}\n\n**Next step.**\n\n```\n{f.action}\n```\n\n"
            f"**Origin.** {origin}\n\n**Verified before writing.**\n\n" + "\n".join(f"- {c}" for c in checks) + "\n\n"
            f"**Files this proposal changes** (under `files/`, mirroring the repository):\n\n{listed}\n\n"
            f"**Apply.** `rasd advise --apply {f.id}` copies the files into the working tree and runs the gates that concern them; "
            "review the diff, run `rasd ci`, commit through a pull request. Nothing is committed or pushed by the agent.\n")
    (folder / "PROPOSAL.md").write_text(body, encoding="utf-8")
    return folder


def propose(f: Finding, model: Model | None) -> Path:
    origin = "computed from the repository's own measurements"
    if f.proposal == "tests":
        det = find_detection(f.data["detection"])
        files, checks = draft_tests(f, det)
    elif f.proposal == "tuning":
        det = find_detection(f.data["detection"])
        files, checks = draft_tuning(f, det)
    elif f.proposal == "scaffold":
        files, checks = draft_scaffold(f, model)
        origin += ("; a model draft was tried and gated" if model else "")
    elif f.proposal == "rule-edit":
        det = find_detection(f.data["detection"])
        files, checks = draft_rule_edit(f, det, model)
        origin += ("; a model edit was tried and gated" if model else "")
    elif f.proposal == "decoy":
        files, checks = draft_decoy(f)
    elif f.proposal == "commands":
        files, checks = {}, ["a procedure, not a file change: the commands are the proposal"]
    else:
        raise ProposalError(f"finding {f.id} has nothing the agent can draft; its next step is written in the counsel")
    return write_proposal(f, files, checks, origin)


def apply_proposal(finding_id: str, by: str | None) -> int:
    folder = PROPOSALS / slug(finding_id)
    if not (folder / "PROPOSAL.md").exists():
        raise SystemExit(f"no proposal for {finding_id}: rasd advise --propose {finding_id}")
    files = sorted(p for p in (folder / "files").rglob("*") if p.is_file())
    if not files:
        print(f"{YELLOW}the proposal changes no file; follow {_rel(folder / 'PROPOSAL.md')}{RESET}")
        return 0
    touched: set[str] = set()
    scaffolded: set[str] = set()
    for p in files:                                   # a new detection folder gets the full scaffold first, then the proposal's files
        m = re.match(r"^detect/detections/([^/]+)/rule\.yml$", p.relative_to(folder / "files").as_posix())
        if m and not (ROOT / "detect" / "detections" / m.group(1)).exists():
            tech, name = m.group(1).split("_", 1)
            subprocess.call([sys.executable, str(ROOT / "tools" / "new_detection.py"), tech, name], cwd=ROOT)
            scaffolded.add(m.group(1))
    for p in files:
        rel = p.relative_to(folder / "files")
        target = ROOT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, target)
        touched.add(rel.as_posix())
        print(f"  {GREEN}wrote{RESET} {rel.as_posix()}")
    dets = sorted({m.group(1) for rel in touched for m in [re.match(r"^detect/(?:detections|correlations)/([^/]+)/", rel)] if m})
    rc = 0
    py = sys.executable
    for det_id in dets:
        folder_ = ROOT / "detect" / "detections" / det_id
        if det_id in scaffolded or not (folder_ / "contract.yml").exists():
            print(f"\n{YELLOW}{det_id} is a scaffold: it fails CI until contract.yml, tuning.yml, the tests and the README are "
                  f"complete, by design. Start with: rasd lint; rasd test --filter {det_id}{RESET}")
            continue
        for argv in (["validate.py"], ["run_tests.py", "--filter", det_id], ["prove.py", "--filter", det_id],
                     ["certify.py", "--filter", det_id, "--check"], ["tune.py", "--filter", det_id, "--check"],
                     ["parity.py", "--filter", det_id]):
            print(f"\n{DIM}> rasd {' '.join(argv).replace('.py', '')}{RESET}")
            rc |= subprocess.call([py, str(ROOT / "tools" / argv[0]), *argv[1:]], cwd=ROOT, env={**os.environ, "NO_BANNER": "1"})
    if any(rel.startswith("deceive/") for rel in touched):
        rc |= subprocess.call([py, str(ROOT / "tools" / "deceive.py"), "--check"], cwd=ROOT)
    record_decision(finding_id, "applied", f"applied from agent/proposals/{slug(finding_id)}", by, None)
    if scaffolded and scaffolded >= set(dets):
        print(f"\n{YELLOW}scaffold in place{RESET}: complete it, then rasd ci; commit through a pull request")
    else:
        print(f"\n{GREEN if not rc else RED}{'gates passed' if not rc else 'a gate failed'}{RESET}: review the diff, run rasd ci, "
              "commit through a pull request")
    return rc


