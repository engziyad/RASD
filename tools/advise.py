def slug(text: object) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", str(text).lower())).strip("-") or "x"


def family(finding_id: str) -> str:
    """The family a decision teaches about: `certify.gap`, `backlog`, `nearmiss` ... (the id's leading
    words, never a detection or technique name)."""
    parts = finding_id.split(".")
    fam = parts[0]
    if len(parts) > 2 and re.fullmatch(r"[a-z-]+", parts[1]):
        fam += "." + parts[1]
    return fam


@dataclass
class Finding:
    id: str                              # stable across builds: what decisions refer to
    priority: int                        # 1 now · 2 next · 3 planned · 4 awareness
    pillar: str                          # detect, red, dfir, intel, purple, deceive, evidence, telemetry, coverage
    roles: tuple[str, ...]
    title: str
    evidence: str                        # what was measured, with the numbers
    action: str                          # the next step, a command when there is one
    proposal: str | None = None          # what --propose drafts: tests, tuning, scaffold, rule-edit, decoy, commands
    weight: float = 0.0                  # tie-breaker within a priority: how much the finding covers
    data: dict = field(default_factory=dict)
    base_priority: int = 0
    decision: dict | None = None

    def __post_init__(self) -> None:
        if not self.base_priority:
            self.base_priority = self.priority
        if not FINDING_ID.match(self.id):
            raise ValueError(f"finding id '{self.id}' is not well formed")


def _n(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


def _sentence(text: object) -> str:
    t = " ".join(str(text).split())
    return t if not t or t.endswith((".", "!", "?", ":")) else t + "."


def _short(obj: Any, n: int = 160) -> str:
    text = json.dumps(obj, ensure_ascii=False, default=str)
    return text if len(text) <= n else text[: n - 1] + "…"


def _det_link_label(det_id: str) -> str:
    return f"`{det_id}`"


