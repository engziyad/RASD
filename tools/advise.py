def source_findings(repo) -> list[Finding]:
    """The data sources the most detections depend on: where one collector failing blinds the most."""
    from chain import data_sources
    users: dict[str, list[str]] = defaultdict(list)
    for d in repo.items:
        for src in data_sources(d):
            users[src].append(d.id)
    out = []
    n = len(repo.items)
    for src, dets in sorted(users.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        if len(dets) < max(3, n / 4):
            continue
        techs = sorted({repo.by_id[x].technique for x in dets})
        out.append(Finding(
            id=f"source.{slug(src)}", priority=4, pillar="telemetry", roles=("analyst", "executive"),
            title=f"{src} feeds {len(dets)} of {n} detections",
            evidence=f"If that collector stops, {len(techs)} techniques go dark together: {', '.join(techs)}.",
            action="Alert on the source's own silence in the SIEM and run rasd doctor <export> --profile auto after every collector change.",
            weight=len(dets), data={"source": src, "detections": dets}))
    return out


