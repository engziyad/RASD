def load_decisions(path: Path = DECISIONS) -> dict:
    if not path.exists():
        return {"decisions": []}
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    doc.setdefault("decisions", [])
    return doc


def _iso(value: Any) -> bool:
    if isinstance(value, dt.date):
        return True
    try:
        dt.date.fromisoformat(str(value))
        return True
    except ValueError:
        return False


def decision_errors(doc: dict) -> list[str]:
    where = "agent/decisions.yml"
    errs = []
    rows = doc.get("decisions")
    if not isinstance(rows, list):
        return [f"{where}: `decisions` must be a list"]
    for n, d in enumerate(rows, 1):
        if not isinstance(d, dict):
            errs.append(f"{where} #{n}: not a mapping")
            continue
        fid = str(d.get("finding", ""))
        if not FINDING_ID.match(fid):
            errs.append(f"{where} #{n}: finding '{fid}' is not a finding id")
        if d.get("decision") not in DECISION_KINDS:
            errs.append(f"{where} #{n} ({fid}): decision must be one of {', '.join(DECISION_KINDS)}")
        if not _iso(d.get("date")):
            errs.append(f"{where} #{n} ({fid}): date must be YYYY-MM-DD")
        if d.get("decision") == "rejected" and len(str(d.get("note") or "")) < 10:
            errs.append(f"{where} #{n} ({fid}): a rejection needs a note that says why")
        if d.get("decision") == "deferred" and not _iso(d.get("until")):
            errs.append(f"{where} #{n} ({fid}): a deferral needs `until: YYYY-MM-DD`")
        unknown = set(d) - {"finding", "decision", "date", "by", "note", "until", "source"}
        if unknown:
            errs.append(f"{where} #{n} ({fid}): unknown keys {sorted(unknown)}")
    return errs


def latest_decisions(doc: dict) -> dict[str, dict]:
    """The last decision taken on each finding, in file order."""
    out: dict[str, dict] = {}
    for d in doc.get("decisions") or []:
        if isinstance(d, dict) and d.get("finding"):
            out[str(d["finding"])] = d
    return out


def learned_families(doc: dict) -> dict[str, int]:
    """Families rejected DEMOTE_AFTER times or more; their findings rank one level lower."""
    rejected = Counter(family(fid) for fid, d in latest_decisions(doc).items() if d.get("decision") == "rejected")
    return {fam: n for fam, n in sorted(rejected.items()) if n >= DEMOTE_AFTER}


def apply_decisions(findings: list[Finding], doc: dict, today: dt.date | None = None) -> dict:
    """Rank the findings under the decisions: rejected ones are set aside, deferred ones wait (until
    their date, when `today` is given; always, on the generated page), accepted ones stay ranked and
    carry their decision; a family rejected repeatedly is demoted. Returns the view the renderers use."""
    latest = latest_decisions(doc)
    demoted = learned_families(doc)
    ranked, aside, deferred = [], [], []
    for f in findings:
        f = copy.copy(f)
        f.decision = latest.get(f.id)
        fam = family(f.id)
        if fam in demoted:
            f.priority = min(4, f.base_priority + 1)
        d = f.decision or {}
        kind = d.get("decision")
        if kind == "rejected":
            aside.append(f)
        elif kind == "deferred" and (today is None or not _iso(d.get("until")) or dt.date.fromisoformat(str(d["until"])) > today):
            deferred.append(f)
        else:
            ranked.append(f)
    ranked.sort(key=lambda f: (f.priority, -f.weight, f.id))
    current = {f.id for f in findings}
    accepted = [d for d in latest.values() if d.get("decision") in ("accepted", "applied")]
    resolved = [d for d in accepted if d["finding"] not in current]
    ledger = {"decisions": len(doc.get("decisions") or []), "accepted": len(accepted), "resolved": len(resolved),
              "open": len(accepted) - len(resolved),
              "rejected": sum(1 for d in latest.values() if d.get("decision") == "rejected"),
              "deferred": sum(1 for d in latest.values() if d.get("decision") == "deferred"),
              "resolved_ids": sorted(d["finding"] for d in resolved), "demoted": demoted}
    return {"ranked": ranked, "set_aside": sorted(aside, key=lambda f: f.id), "deferred": sorted(deferred, key=lambda f: f.id),
            "ledger": ledger}


def record_decision(finding_id: str, decision: str, note: str | None, by: str | None, until: str | None,
                    source: str = "person", path: Path = DECISIONS, today: dt.date | None = None) -> dict:
    """Append one decision to agent/decisions.yml, keeping the file's own text and comments."""
    if not FINDING_ID.match(finding_id):
        raise SystemExit(f"'{finding_id}' is not a finding id")
    if decision not in DECISION_KINDS:
        raise SystemExit(f"decision must be one of {', '.join(DECISION_KINDS)}")
    if decision == "rejected" and len(note or "") < 10:
        raise SystemExit("a rejection needs --note with the reason (it is what the agent learns from)")
    if decision == "deferred" and not (until and _iso(until)):
        raise SystemExit("a deferral needs --until YYYY-MM-DD")
    entry = {"finding": finding_id, "decision": decision, "date": (today or dt.date.today()).isoformat()}
    if by:
        entry["by"] = by
    if note:
        entry["note"] = note
    if until:
        entry["until"] = until
    if source != "person":
        entry["source"] = source
    text = path.read_text(encoding="utf-8") if path.exists() else "decisions:\n"
    doc = yaml.safe_load(text) or {}
    if not isinstance(doc.get("decisions"), list) or doc["decisions"] == []:
        # the file holds comments and an empty list: rewrite only the `decisions:` line into a list head
        text = re.sub(r"(?m)^decisions:\s*\[\]\s*$", "decisions:", text)
        if not re.search(r"(?m)^decisions:\s*$", text):
            text = text.rstrip("\n") + "\ndecisions:\n"
    block = yaml.safe_dump([entry], sort_keys=False, allow_unicode=True, width=1000)
    path.parent.mkdir(exist_ok=True)
    path.write_text(text.rstrip("\n") + "\n" + block, encoding="utf-8")
    errs = decision_errors(load_decisions(path))
    if errs:
        raise SystemExit("\n".join(errs))
    return entry


