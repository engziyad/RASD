class ProposalError(Exception):
    pass


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _verdict(rule: dict, ev: dict) -> bool | None:
    try:
        return matches(rule, ev)
    except SigmaError:
        return None


def _tests_of(det: Detection) -> list[tuple[str, dict, bool]]:
    return [(f"TP#{i}", ev, True) for i, ev in enumerate(det.tests("true_positive"), 1)] + \
           [(f"TN#{i}", ev, False) for i, ev in enumerate(det.tests("true_negative"), 1)]


def _append_jsonl(folder: Path, kind: str, event: dict) -> str:
    text = (folder / "tests" / f"{kind}.jsonl").read_text(encoding="utf-8") if (folder / "tests" / f"{kind}.jsonl").exists() else ""
    return text.rstrip("\n") + ("\n" if text.strip() else "") + json.dumps(event, ensure_ascii=False) + "\n"


def draft_tests(f: Finding, det: Detection) -> tuple[dict[str, str], list[str]]:
    """A true positive or true negative the engine confirms, appended to the detection's tests."""
    event, expect = f.data.get("event"), f.data.get("expect")
    if not isinstance(event, dict) or expect not in ("true_positive", "true_negative"):
        raise ProposalError("the finding carries no event to add")
    event = {"_case": f"counsel: {f.data.get('reason', f.id)}", **{k: v for k, v in event.items() if k != "_case"}}
    got = _verdict(det.rule, event)
    if got is None or got != (expect == "true_positive"):
        raise ProposalError(f"the engine does not read the event as a {expect.replace('_', ' ')}; nothing written")
    bare = {k: v for k, v in event.items() if k != "_case"}
    if any({k: v for k, v in ev.items() if k != "_case"} == bare for _l, ev, _e in _tests_of(det)):
        raise ProposalError("an identical test event already exists")
    files = {_rel(det.folder / "tests" / f"{expect}.jsonl"): _append_jsonl(det.folder, expect, event)}
    return files, [f"the engine confirms the event is a {expect.replace('_', ' ')} of {det.id}",
                   f"existing suite unchanged: {len(_tests_of(det))} events"]


def _field_value(ev: dict, field: str) -> Any:
    return next((v for k, v in ev.items() if k.lower() == field.lower()), None)


def _with_field(ev: dict, field: str, value: Any) -> dict:
    key = next((k for k in ev if k.lower() == field.lower()), field)
    return {**ev, key: value}


def _satisfying(key: str, value: Any, current: Any) -> Any | None:
    """A value of the field that satisfies one filter condition `key: value`, built from the event's current
    value so the rest of the rule still reads the event the same way; None when the modifier cannot be
    satisfied by construction (regular expressions, encodings)."""
    mods = [m for m in key.split("|")[1:] if m not in ("cased", "all", "windash")]
    v = str(value)
    cur = current if isinstance(current, str) else ""
    if not mods:
        return value
    if mods == ["contains"]:
        return f"{cur} {v}" if cur else f"x{v}x"
    if mods == ["endswith"]:
        if "\\" in cur and v.startswith("\\"):
            return cur.rsplit("\\", 1)[0] + v
        return cur + v if cur and not v.startswith("\\") else "C:\\x" + v
    if mods == ["startswith"]:
        return v + cur
    return None


def filter_tests(det: Detection, tuned: dict, name: str, selection: dict, label: str) -> tuple[list[dict], list[dict]]:
    """The tests an applied filter must come with, built from the detection's own true positives and confirmed by
    the engine: for every value of the filter a look-alike true negative that only the filter decides (the rule
    without the filter fires on it, the tuned rule stays quiet), and for every condition of the filter a true
    positive that satisfies every other condition but not that one (the filter must not apply to it). Without
    them the linter's filter coverage and the rule mutation proof refuse the tuning."""
    tps = det.tests("true_positive")
    conditions = [(k, v if isinstance(v, list) else [v]) for k, v in selection.items()]
    fields = [k.split("|")[0] for k, _v in conditions]
    tns: list[dict] = []
    for ci, (key, values) in enumerate(conditions):
        for value in values:
            made = None
            for tp in tps:
                ev = {k: v for k, v in tp.items() if k != "_case"}
                ok = True
                for cj, (key2, values2) in enumerate(conditions):
                    chosen = value if cj == ci else values2[0]
                    sat = _satisfying(key2, chosen, _field_value(ev, key2.split("|")[0]))
                    if sat is None:
                        ok = False
                        break
                    ev = _with_field(ev, key2.split("|")[0], sat)
                if ok and _verdict(det.rule, ev) is True and _verdict(tuned, ev) is False:
                    made = ev
                    break
            if made is None:
                raise ProposalError(f"could not build a look-alike true negative for {key}: {value!r}; write it by hand")
            bare = {k: v for k, v in made.items() if k != "_case"}
            if not any({k: v for k, v in t.items() if k != "_case"} == bare for t in tns):
                tns.append({"_case": f"tuning {label}: look-alike that only {name} decides ({key.split('|')[0]} {value})", **made})
    new_tps: list[dict] = []
    if len(conditions) > 1:
        for ci, (key, _values) in enumerate(conditions):
            made = None
            for tp in tps:
                ev = {k: v for k, v in tp.items() if k != "_case"}
                ok = True
                for cj, (key2, values2) in enumerate(conditions):
                    if cj == ci:
                        continue
                    sat = _satisfying(key2, values2[0], _field_value(ev, key2.split("|")[0]))
                    if sat is None:
                        ok = False
                        break
                    ev = _with_field(ev, key2.split("|")[0], sat)
                if ok and _verdict(tuned, ev) is True:
                    made = ev
                    break
            if made is None:
                raise ProposalError(f"could not build a true positive that {key} alone keeps out of the filter; write it by hand")
            new_tps.append({"_case": f"tuning {label}: {fields[ci]} differs, so {name} must not apply", **made})
    return tns, new_tps


def _rule_text_with_filter(text: str, rule: dict, name: str, selection: dict) -> str:
    """rule.yml with a new filter selection before `condition:`, as text, so the rest of the file keeps its
    formatting. The condition gains `and not <name>` unless it already negates every filter_* selection
    (then the new one is covered and a second negation would be a redundant operand prove would flag).
    The result is verified to read back as the tuned rule."""
    from tune import negated_selections, with_filter
    lines = text.split("\n")
    idx = next((i for i, ln in enumerate(lines) if re.match(r"^  condition:", ln)), None)
    if idx is None or isinstance(rule["detection"]["condition"], list):
        raise ProposalError("rule.yml has no single `  condition:` line to extend")
    block = yaml.safe_dump({name: selection}, sort_keys=False, allow_unicode=True, default_flow_style=False, width=1000)
    inserted = ["  " + ln for ln in block.rstrip("\n").split("\n")]
    covered = copy.deepcopy(rule)
    covered["detection"][name] = selection
    if name in negated_selections(covered):
        want = covered
        lines[idx:idx] = inserted
    else:
        want = with_filter(rule, name, selection)
        m = re.match(r"^  condition:\s*(.*)$", lines[idx])
        if m is None:
            raise ProposalError("rule.yml has no readable `  condition:` line")
        cond = m.group(1).strip().strip("'\"")
        lines[idx:idx + 1] = [*inserted, f"  condition: ({cond}) and not {name}"]
    new_text = "\n".join(lines)
    got = yaml.safe_load(new_text)
    if got.get("detection") != want["detection"]:
        raise ProposalError("the edited rule text does not read back as the tuned rule")
    return new_text


def draft_tuning(f: Finding, det: Detection) -> tuple[dict[str, str], list[str]]:
    """Apply a proposed tuning that the corpus measured SAFE: the filter enters rule.yml, the entry becomes
    applied, and a corpus alert it removes becomes a true negative that proves it."""
    from tune import DEFAULT_LOGS, analyse, load_tuning, noise_events, with_filter
    doc = load_tuning(det)
    entry = next((t for t in doc.get("tunings") or [] if t.get("id") == f.data.get("tuning")), None)
    if not entry or entry.get("status") != "proposed":
        raise ProposalError("the tuning is not a proposed entry of tuning.yml")
    row = next((r for r in analyse(det, DEFAULT_LOGS) if r["id"] == entry["id"]), None)
    if not row or row["verdict"] != "SAFE":
        raise ProposalError("the tuning does not measure SAFE on the replay corpus today; nothing written")
    name = f"filter_{entry['id']}"
    if name in det.rule["detection"]:
        raise ProposalError(f"rule.yml already has a selection named {name}")
    rule_text = _rule_text_with_filter((det.folder / "rule.yml").read_text(encoding="utf-8"), det.rule, name, entry["filter"])
    tuned = yaml.safe_load(rule_text)
    for ev in [ev for _l, ev, _e in _tests_of(det)] + noise_events(DEFAULT_LOGS, det.rule):
        if _verdict(tuned, ev) != _verdict(with_filter(det.rule, name, entry["filter"]), ev):
            raise ProposalError("the written rule and the measured tuning disagree on an event; nothing written")
    for label, ev, exp in _tests_of(det):
        if _verdict(tuned, ev) != exp:
            raise ProposalError(f"the filter changes the verdict of {label}; nothing written")
    breaks = spec_breaks(det, tuned)
    if breaks:
        raise ProposalError("the filter contradicts the behaviour spec (" + "; ".join(breaks) + "): declare the exclusion in "
                            "behavior.yml with its reason first, or keep the suppression in the SIEM; nothing written")
    tns, new_tps = filter_tests(det, tuned, name, entry["filter"], entry["id"])
    removed = [ev for ev in noise_events(DEFAULT_LOGS, det.rule) if _verdict(det.rule, ev) and not _verdict(tuned, ev)]
    if removed:
        tns.append({"_case": f"tuning {entry['id']}: {' '.join(str(entry.get('reason', '')).split())[:120]}",
                    **{k: v for k, v in removed[0].items() if k != "_case"}})
    from validate import unexercised_filters
    old_tns = det.tests("true_negative")
    if unexercised_filters(tuned, old_tns + tns):
        raise ProposalError("the look-alike true negatives do not exercise the filter; nothing written")
    score, survivors = proof_with(det, tuned, new_tps, tns)
    if score < 100:
        raise ProposalError(f"the tuned rule's mutation proof would be {score:.0f}%, not 100% (surviving: {'; '.join(survivors)}); "
                            "nothing written")
    tuning_text = (det.folder / "tuning.yml").read_text(encoding="utf-8")
    ydoc = yaml.safe_load(tuning_text)
    for t in ydoc["tunings"]:
        if t.get("id") == entry["id"]:
            t["status"], t["selection"] = "applied", name
            t.pop("filter", None)
            t.pop("residual_risk", None)
    header = tuning_text.split("\n", 1)[0] + "\n" if tuning_text.startswith("#") else ""
    files = {_rel(det.folder / "rule.yml"): rule_text,
             _rel(det.folder / "tuning.yml"): header + yaml.safe_dump(ydoc, sort_keys=False, allow_unicode=True, width=1000)}
    tn_text = (det.folder / "tests" / "true_negative.jsonl").read_text(encoding="utf-8").rstrip("\n") + "\n"
    files[_rel(det.folder / "tests" / "true_negative.jsonl")] = tn_text + "".join(json.dumps(ev, ensure_ascii=False) + "\n" for ev in tns)
    if new_tps:
        tp_text = (det.folder / "tests" / "true_positive.jsonl").read_text(encoding="utf-8").rstrip("\n") + "\n"
        files[_rel(det.folder / "tests" / "true_positive.jsonl")] = tp_text + "".join(json.dumps(ev, ensure_ascii=False) + "\n" for ev in new_tps)
    checks = [f"filter {name} = {json.dumps(entry['filter'], ensure_ascii=False)} hides none of {row['tested']} attack variants",
              f"removes {row['removed']} of {row['alerts']} alerts of the replay corpus",
              "every test keeps its verdict and the behaviour certificate holds with the filter in the rule",
              f"{_n(len(tns), 'look-alike true negative')} built from the rule's own true positives, each fired on by the rule and "
              f"kept quiet by the filter (engine-confirmed)"
              + (f"; {_n(len(new_tps), 'true positive')} that the filter must not cover" if new_tps else ""),
              f"with them the filter is exercised (linter) and the rule mutation proof stays at {score:.0f}%"]
    return files, checks


def _logsource_guess(telemetry: str) -> dict:
    t = telemetry.lower()
    if "sysmon for linux" in t:
        return {"product": "linux", "category": "process_creation"}
    if "access log" in t or ("web" in t and "log" in t):
        return {"category": "webserver"}
    if "security" in t or re.search(r"\b4\d{3}\b", t):
        return {"product": "windows", "service": "security"}
    return {"product": "windows", "category": "process_creation"}


