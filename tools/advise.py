def environment_counsel(logs: list[Path], profile: str | None, noisy_per_day: float = NOISY_PER_DAY) -> tuple[list[Finding], dict]:
    """What your own telemetry says: blind or degraded detections, noisy rules and the tunings that would
    quiet them, storylines, and the boundaries your traffic sits on. Returns the findings and a summary
    of counts (no values from the logs)."""
    import doctor
    import nearmiss
    import profiles
    import replay
    from tune import analyse as analyse_tuning
    raw = [e for p in logs for e in load_jsonl(p)]
    events, used = profiles.apply(raw, profile)
    dets, corrs = load_detections(), load_correlations()
    out: list[Finding] = []
    label = " ".join(str(p) for p in logs)
    if not profile:
        best, scores = profiles.detect(raw)
        if best != profiles.NATIVE and scores[best] > scores[profiles.NATIVE]:
            out.append(Finding(id=f"profile.{slug(best)}", priority=1, pillar="telemetry", roles=("analyst",),
                               title=f"The export looks like the {best} profile; read it with --profile {best}",
                               evidence=f"{scores[best]} of {min(len(raw), 500)} sampled events reach a RASD log source with it, "
                                        f"{scores[profiles.NATIVE]} without.",
                               action=f"rasd advise --logs {label} --profile {best}", weight=scores[best], data={"profile": best}))
    diag = doctor.diagnose(events, [*dets, *[SimpleNamespace(id=c.id, rule=c.base, contract=c.contract) for c in corrs]], used)
    from chain import data_sources
    by_id_all: dict[str, Any] = {x.id: x for x in dets}
    by_id_all.update({c.id: c for c in corrs})
    for r in diag:
        if r["verdict"] == "READY":
            continue
        d = by_id_all.get(r["detection"])
        reads = ", ".join(data_sources(d)) if d is not None else r["logsource"]
        where = f"detect/{'correlations' if isinstance(d, Correlation) else 'detections'}/{r['detection']}/README.md"
        if r["fixes"]:
            fixes = "; ".join(r["fixes"])
        elif r["events"] == 0:
            fixes = f"Forward {reads} into the export; the 'Telemetry required' section of {where} names the collector and audit setting."
        elif any("never appears" in i for i in r["issues"]):
            fixes = f"Enable the audit policy that writes {reads} on the hosts that matter; {where} names it under 'Telemetry required'."
        else:
            fixes = f"rasd doctor {label} --profile {used} --filter {r['detection']}"
        out.append(Finding(
            id=f"telemetry.{r['detection']}", priority=1 if r["verdict"] == "BLIND" else 2, pillar="telemetry", roles=("analyst",),
            title=f"{r['detection']} is {r['verdict'].lower()} on this telemetry",
            evidence=f"{r['events']} events of log source {r['logsource']} in the export; " + ("; ".join(r["issues"]) or "no issue recorded"),
            action=fixes, weight=1 if r["verdict"] == "BLIND" else 0.5, data={"detection": r["detection"], "verdict": r["verdict"]}))
    alerts, stats = replay.replay(events, dets, {}, None, corrs)
    fc = replay.forecast(alerts, stats, [*dets, *corrs], noisy_per_day)
    by_id = {d.id: d for d in dets}
    for row in fc:
        if not row["verdict"].startswith("noisy"):
            continue
        d = by_id.get(row["rule"])
        safe = []
        if d is not None and (d.folder / "tuning.yml").exists():
            safe = [t for t in analyse_tuning(d, logs) if t["verdict"] == "SAFE" and t["status"] == "proposed" and t["removed"]]
        quiet = "; ".join(f"proposed tuning {t['id']} would remove {t['removed']} of {t['alerts']} alerts and hide no attack variant"
                          for t in safe)
        out.append(Finding(
            id=f"noise.{row['rule']}", priority=2, pillar="dfir", roles=("analyst",),
            title=f"{row['rule']}: {row['alerts']} alerts ({row['per_day']}/day) on {row['entities']} entities - tune before deploying",
            evidence=f"Replay of {stats['events']} events ({stats['routed']} routed). " + (quiet or "No proposed tuning removes them."),
            action=(f"rasd advise --propose tune.proposed.{row['rule']}.{slug(safe[0]['id'])}" if safe else
                    f"rasd tune --filter {row['rule']} --logs {label}; add a proposed tuning to tuning.yml and measure it there."),
            weight=row["alerts"], data={"detection": row["rule"], "alerts": row["alerts"], "safe_tunings": [t["id"] for t in safe]}))
    stories = replay.storylines(alerts, 60)          # already only the entities with two or more techniques
    if stories:
        top = stories[0]
        techs = sorted({a["technique"] for a in top["steps"]})
        out.append(Finding(
            id="replay.storylines", priority=2, pillar="dfir", roles=("analyst",),
            title=f"{len(stories)} storyline{'s' if len(stories) != 1 else ''} chain two or more techniques on one entity",
            evidence=f"The highest scored spans {len(techs)} techniques ({', '.join(techs)}) in {top['alerts']} alerts "
                     f"within {top['minutes']:.0f} minutes.",
            action=f"rasd replay {label} --profile {used} --case-dir reports/cases", weight=len(stories),
            data={"storylines": len(stories)}))
    near = nearmiss.analyse(events)
    for det_id, r in sorted(near["detections"].items()):
        for b in r.get("boundaries") or []:
            if b["pinned_by"] or b["events"] < 1:
                continue
            out.append(Finding(
                id=f"nearmiss.env.{det_id}.{slug(b['condition'])}", priority=3, pillar="detect", roles=("engineer", "analyst"),
                title=f"{det_id}: {b['events']} of your events ({b['share']}%) are one edit away from an alert, held back by {b['condition']}",
                evidence=f"No true negative pins that boundary; the edit is {b['witness']['field']}.",
                action=f"rasd nearmiss {label} --profile {used} --filter {det_id} --suggest", weight=b["events"],
                data={"detection": det_id}))
    for cid, r in sorted(near["correlations"].items()):
        if r.get("headroom") is not None and r["headroom"] <= 1 and r.get("windows"):
            out.append(Finding(
                id=f"headroom.env.{cid}", priority=2, pillar="detect", roles=("analyst",),
                title=f"{cid}: your quietest window sits {r['headroom']} {r['unit']} under the threshold",
                evidence=f"Threshold {r['threshold']} {r['unit']} per {r['window']}; the busiest quiet window reached {r['max_quiet']}.",
                action=f"rasd nearmiss {label} --profile {used} --filter {cid}; raise the threshold or narrow the grouping before deploying.",
                weight=r["threshold"], data={"detection": cid}))
    tally = Counter(r["verdict"] for r in diag)
    summary = {"events": len(events), "profile": used, "routed": stats["routed"], "unrouted": stats["unrouted"],
               "alerts": len(alerts), "storylines": len(stories),
               "telemetry": {"ready": tally.get("READY", 0), "degraded": tally.get("DEGRADED", 0), "blind": tally.get("BLIND", 0)},
               "noisy": sorted(r["rule"] for r in fc if r["verdict"].startswith("noisy")),
               "silent": sorted(r["rule"] for r in fc if r["verdict"] == "silent")}
    return out, summary


