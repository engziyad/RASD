def wave_of(test: dict, step: dict) -> str:
    params = set(step.get("parameters") or [])
    if test.get("platform") in ("linux", "web"):
        return test["platform"]
    if "Target" in params:
        return "target"
    if params & {"Spn", "UserList"}:
        return "dc"
    return "opt_in" if step.get("opt_in") else "windows"


def binding_of(repo: Repo, det, step: dict, wave: str) -> str:
    token = det.id in (step.get("bind") or {})
    if isinstance(det, Correlation):
        return "enough base events from the lab host's address in one window"
    if wave == "target":
        return "logged on the target, carries the run token"
    if logsource_key(det.rule) == "opencanary/honeypot":
        return "logged on the decoy; the client address (src_host) is the lab host"
    eids = {int(v) for sel in det.rule["detection"].values() if isinstance(sel, dict)
            for k, v in sel.items() if k.split("|")[0] == "EventID" and str(v).isdigit()}
    if eids & NETWORK_EVENTS:
        return "client address is the lab host"
    return "logged on the lab host" + (", carries the run token" if token else "")


def render_evidence_plan(repo: Repo) -> str:
    n = len(repo.items)
    validated = [d for d in repo.items if repo.evidence[d.id]]
    out = HEADER + "# Evidence Plan\n\n"
    out += ("How every detection moves from SIEM-Ready to Validated: the lab machine, the offensive step that produces "
            "the attack, the logs to export and how `rasd evidence` binds them to the run. A status changes only when the "
            "detection's `evidence.md` is committed; nothing here is estimated.\n\n")
    ops = ops_average(repo, validated)
    out += (f"**Progress:** {len(validated)}/{n} detections Validated (lab evidence) · Operational Score "
            + (f"{ops:.0f}/100" if ops is not None else "pending") + ".\n")
    rows: dict[str, list[str]] = defaultdict(list)
    reached = set()
    for t in repo.red:
        for step in t.get("steps") or []:
            names = list(step.get("detections") or []) + list(step.get("correlations") or [])
            for det_id in names:
                det = repo.by_id.get(det_id)
                if not det:
                    continue
                reached.add(det_id)
                wave = wave_of(t, step)
                ev = repo.evidence[det_id]
                status = f"FIRED · {str(ev.get('run_utc', ''))[:10]}" if ev else "pending"
                kind = " (correlation)" if isinstance(det, Correlation) else ""
                rows[wave].append(f"| [{det_id}](../{det_path(det)}/){kind} | [{t['id']}](../red/{t['platform']}/{t['id']}/)"
                                  f" · `{step['id']}` | {binding_of(repo, det, step, wave)} | {status} |")
    for number, (key, title, machine, commands) in enumerate([w for w in WAVES if rows[w[0]]], 1):
        out += f"\n## {number} · {title}\n\n{machine}\n\n" + "\n".join(f"- {c}" for c in commands) + "\n\n"
        out += "| Detection | Red test · step | Bound to the run by | Status |\n|---|---|---|---|\n" + "\n".join(rows[key]) + "\n"
    missing = [d for d in repo.items if d.id not in reached]
    if missing:
        out += ("\n## Not reachable by an offensive step yet\n\nNo red step names these detections, so no lab run can "
                "produce their evidence until one does.\n\n| Detection | What it needs |\n|---|---|\n")
        for d in missing:
            need = (f"a burst that reaches its threshold ({repo.det_facts(d)['describe']}) from the lab host"
                    if isinstance(d, Correlation) else "a red test step that names it")
            out += f"| [{d.id}](../{det_path(d)}/) | {need} |\n"
    out += ("\n## Turn the run into evidence\n\n```bash\n"
            "rasd doctor red/results/lab-<timestamp>/lab-export.jsonl\n"
            "rasd evidence --run red/results/lab-<timestamp>.zip dc-export.jsonl target-export.jsonl "
            "siem-alerts.csv\n"
            "rasd build\n```\n\n"
            "`--run` refuses a zip that differs from the `.sha256` beside it and any file that differs from the run's "
            "manifest before it reads anything. Linux and web runs write their own `emulation-results.json`; run "
            "`rasd evidence --run` once per run folder with its exports. Commit only the `evidence.md` files; the raw exports stay with you. Details: "
            "[OPERATIONAL_VALIDATION](OPERATIONAL_VALIDATION.md) · [lab kit](../red/lab/README.md).\n")
    return out + FOOTER


def replace_block(text: str, start: str, end: str, block: str, after_title: bool = False) -> str:
    if start in text and end in text:
        return text.split(start)[0] + block + text.split(end, 1)[1]
    if after_title:
        lines = text.split("\n", 1)
        return lines[0] + "\n\n" + block + "\n" + (lines[1] if len(lines) > 1 else "")
    return text


def outputs(repo: Repo) -> dict[Path, str]:
    out = {
        PURPLE / "validation_matrix.md": render_validation_matrix(repo),
        PURPLE / "attack_to_detection_map.md": render_attack_map(repo),
        PURPLE / "evidence_matrix.md": render_evidence_matrix(repo),
        PURPLE / "detection_latency.md": render_latency(repo),
        DOCS / "RASD_METRICS.md": render_metrics(repo),
        DOCS / "DATA_SOURCE_COVERAGE.md": render_data_sources(repo),
        PURPLE / "executive_matrix.md": render_executive_matrix(repo),
        DOCS / "EVIDENCE_PLAN.md": render_evidence_plan(repo),
        INTEL / "outputs" / "detection_backlog.md": render_backlog(repo),
        **render_intel_maps(repo),
    }
    for d in repo.items:
        readme = d.folder / "README.md"
        text = readme.read_text(encoding="utf-8") if readme.exists() else f"# {d.title}\n"
        facts = render_corr_facts(repo, d) if isinstance(d, Correlation) else render_facts(repo, d)
        out[readme] = replace_block(text, FACTS_START, FACTS_END, facts, after_title=True)
    root_readme = ROOT / "README.md"
    if root_readme.exists():
        text = replace_block(root_readme.read_text(encoding="utf-8"), README_START, README_END, render_readme_metrics(repo))
        out[root_readme] = replace_block(text, STATUS_START, STATUS_END, render_status(repo))
    summary = DOCS / "EXECUTIVE_SUMMARY.md"
    if summary.exists():
        out[summary] = replace_block(summary.read_text(encoding="utf-8"), EXEC_START, EXEC_END, render_executive_block(repo))
    dreadme = DFIR / "README.md"
    if dreadme.exists():
        out[dreadme] = replace_block(dreadme.read_text(encoding="utf-8"), DFIR_START, DFIR_END, render_dfir_catalog(repo))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail on chain gaps, maturity over-claims or stale files")
    args = ap.parse_args()
    repo = Repo()

    print(f"{BOLD}Attack-to-defense chain · {len(repo.techniques())} techniques · {len(repo.dets)} detections · "
          f"{len(repo.corrs)} correlations · {len(repo.red)} offensive tests{RESET}\n")
    for t in repo.techniques():
        c = repo.checklist(t)
        done = sum(v == "done" for v in c.values())
        pend = [k for k, v in c.items() if v == "pending"]
        miss = [k for k, v in c.items() if v == "missing"]
        colour = GREEN if not miss else RED
        detail = (f"{RED}missing: {', '.join(miss)}{RESET}" if miss else "") + \
                 (f"  {YELLOW}pending lab run: {', '.join(pend)}{RESET}" if pend else "")
        print(f"  {colour}{done:>2}/20{RESET}  {t:<10} {DIM}{TECHNIQUE_NAMES.get(t, '')}{RESET}  {detail}")
    print()
    for d in repo.items:
        print(f"  {repo.maturity(d):<12} {d.id}" + (f" {DIM}(correlation){RESET}" if isinstance(d, Correlation) else ""))

    errs = gate_errors(repo)
    files = outputs(repo)
    stale = [p for p, body in files.items() if not p.exists() or p.read_text(encoding="utf-8") != body]
    if args.check:
        for p in stale:
            errs.append(f"{p.relative_to(ROOT)} is out of date (run: rasd chain)")
    else:
        for p, body in files.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(body, encoding="utf-8")
    if errs:
        print(f"\n{RED}{len(errs)} chain problem(s){RESET}")
        for e in errs:
            print(f"  - {e}")
        return 1
    print(f"\n{GREEN}chain complete{RESET} {DIM}(pending items need a real lab run - they are never estimated){RESET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
