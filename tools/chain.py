def front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    return (yaml.safe_load(text[4:end]) or {}) if end != -1 else {}


def load_docs(folder: Path) -> list[dict]:
    out = []
    for p in sorted(folder.glob("*.md")):
        fm = front_matter(p)
        if fm:
            out.append({**fm, "_path": p, "_text": p.read_text(encoding="utf-8")})
    return out


def technique_link(t: str) -> str:
    return f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)"


def rel(target: Path, start: Path) -> str:
    import os
    return os.path.relpath(target, start).replace(os.sep, "/")


def rule_of(det) -> dict:
    """The Sigma rule that reads the events: a correlation's base rule, a detection's own rule."""
    return det.base if isinstance(det, Correlation) else det.rule


def det_path(det) -> str:
    """Repository path of the detection folder."""
    return f"detect/{'correlations' if isinstance(det, Correlation) else 'detections'}/{det.id}"


def query_path(det, backend: str) -> str:
    sub = "correlations/" if isinstance(det, Correlation) else ""
    return f"queries/{backend}/{sub}{det.id}.{backend}"


def data_sources(det) -> list[str]:
    rule = rule_of(det)
    key = logsource_key(rule)
    if key in LOGSOURCE_LABEL:
        return [LOGSOURCE_LABEL[key]]
    eids = sorted({str(v) for sel in rule["detection"].values() if isinstance(sel, dict)
                   for k, v in sel.items() if k.split("|")[0] == "EventID"})
    channel = key.split("/")[-1].capitalize()
    return [f"{channel} EID {e}" for e in eids] or [key]


