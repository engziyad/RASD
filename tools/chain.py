def public_cell(repo: Repo, d, link: str = "public_evidence.md") -> str:
    """One detection's public dataset result, as the facts blocks and matrices show it."""
    v = repo.public.get(d.id) or {}
    if not v.get("expected"):
        return f"no public dataset records it yet · [why]({link})"
    fp = v["false_positives"]
    sample = " · in-sample (changed after replaying them)" if v.get("changed") else ""
    h = v.get("holdout") or {}
    held = f" · held-out: {len(h['met'])} of {len(h['expected'])}" if h.get("expected") else ""
    return (f"fires on {len(v['independent'])} of {v['recordings']} public recordings of its behaviour{held} · "
            f"{v['alerts']} alert{'' if v['alerts'] == 1 else 's'} · "
            f"{fp} labelled false positive{'' if fp == 1 else 's'}{sample} · [evidence]({link})")


def public_counts(repo: Repo) -> dict:
    vals = list(repo.public.values())
    return {"validated": sum(1 for v in vals if v.get("validated")), "alerts": sum(v.get("alerts", 0) for v in vals),
            "false_positives": sum(v.get("false_positives", 0) for v in vals), "benign": sum(v.get("benign", 0) for v in vals),
            "harness": sum(v.get("harness", 0) for v in vals),
            "holdout_expected": sum(len((v.get("holdout") or {}).get("expected") or []) for v in vals),
            "holdout_met": sum(len((v.get("holdout") or {}).get("met") or []) for v in vals),
            "holdout_files": sum(1 for ds in repo.public_catalog.datasets if ds.holdout),
            "holdout_files_expecting": len({x for v in vals for x in (v.get("holdout") or {}).get("expected") or []}),
            "datasets": sum(1 for ds in repo.public_catalog.datasets if not ds.holdout),
            "sources": len(repo.public_catalog.sources)}


def attack_cell(item) -> str:
    """The primary technique with its ATT&CK name and tactics, then each related technique the rule tags: every
    page shows a technique with the tactics ATT&CK lists for it (TECHNIQUES in tools/common.py)."""
    def one(t: str) -> str:
        return f"{technique_link(t)} {TECHNIQUE_NAMES.get(t, '')} ({', '.join(TECHNIQUE_TACTICS.get(t, ())) or '-'})"
    tagged = [str(x).split(".", 1)[1].upper() for x in item.rule.get("tags") or [] if re.match(r"^attack\.t\d{4}", str(x))]
    related = [t for t in dict.fromkeys(tagged) if t != item.technique]
    return one(item.technique) + "".join(f" · related: {one(t)}" for t in related)


