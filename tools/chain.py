def render_latency(repo: Repo) -> str:
    out = HEADER + ("# Detection Latency\n\nMeasured from the start of the emulation step. *Telemetry* is the time until "
                    "the matching event was written on the host; *SIEM alert* is the time until the SIEM raised the alert "
                    "(scored); *SIEM pipeline* is event → alert: forwarding, indexing and the wait for the scheduled "
                    "search, which runs every 5 minutes in the RASD Splunk app. SIEM columns need an alert export given "
                    "to `rasd evidence`.\n\n")
    out += "| Detection | Telemetry latency | SIEM alert latency | SIEM pipeline delay | Latency points |\n|---|---|---|---|---|\n"
    for d in repo.items:
        ev = repo.evidence[d.id]
        if not ev:
            out += f"| {d.id} | pending | pending | - | - |\n"
            continue
        siem = (ev.get("siem") or {}).get("latency_seconds")
        pipe = (ev.get("siem") or {}).get("pipeline_seconds")
        pts = repo.scores[d.id]["operational"]["Detection latency"]
        out += (f"| {d.id} | {ev.get('latency_seconds', '-')} s | {f'{siem} s' if siem is not None else 'not provided'} | "
                f"{f'{pipe} s' if pipe is not None else '-'} | {pts}/15 |\n")
    out += ("\nTargets: ≤ 60 s earns 15 points, ≤ 5 min 10, ≤ 15 min 5 (see [QUALITY_MODEL.md](../docs/QUALITY_MODEL.md)). "
            "For a correlation, telemetry latency runs to the event that made it reach its threshold, and its Splunk "
            "alert runs once per window, after the window closes.\n")
    return out + FOOTER


