"""
chain.py - the attack-to-defense chain: is every technique complete, end to end?

RASD maps each technique across offensive validation, telemetry, detection, triage,
response, intelligence context and operational evidence. chain.py reads every part of
the repository - red tests, detections, DFIR playbooks, purple scenarios, the intel maps,
evidence files - and answers, per technique, the 20-point completeness map:

   1 Red emulation          8 Mutation tests        15 Evidence file
   2 Expected telemetry     9 Triage guide          16 Engineering Score (100)
   3 Detection rule        10 Response guide        17 Operational Score (>= 80)
   4 SPL query             11 DFIR playbook         18 Coverage depth
   5 KQL query             12 CTI mapping           19 Known blind spots
   6 TP tests              13 Purple scenario       20 Data source requirements
   7 TN tests              14 Cleanup steps

It computes each detection's maturity level (Draft, Tested, Hardened, SIEM-Ready,
Validated, Reference) from those facts - correlation detections included, from what
`rasd correlate` proves - and fails when a contract declares more than the repository can
prove. It generates:

  purple/validation_matrix.md        the matrix: Red | Telemetry | Detect | DFIR | Intel | Evidence | Status
  purple/attack_to_detection_map.md  technique -> red test -> telemetry -> detections -> queries -> playbook
  purple/evidence_matrix.md          operational evidence per detection
  purple/detection_latency.md        measured latency per detection (from evidence)
  docs/RASD_METRICS.md               repository metrics, all counted, none typed
  docs/DATA_SOURCE_COVERAGE.md       every data source, who depends on it, what breaks without it
  intel/mappings/*.md                technique map, data sources per technique, actor tradecraft map
  intel/outputs/detection_backlog.md the gaps ranked for the next rules (backlog.yml + actors.yml)
  detect/detections/<id>/README.md   the facts block at the top of every detection README
  detect/correlations/<id>/README.md the same for every correlation detection
  dfir/README.md                     the playbook catalogue
  purple/executive_matrix.md         per technique: attack emulated, detections, proof, evidence, guidance
  docs/EVIDENCE_PLAN.md              per lab machine: the red steps, exports and status of every detection
  README.md                          the status badges and the metrics block
  docs/EXECUTIVE_SUMMARY.md          the numbers block of the executive summary

Gates (--check): declared maturity <= computed, every covered technique has a red test,
DFIR playbook and purple scenario, every playbook has an evidence table and valid links to
detections and tests, every scenario links existing detections, every actor technique is
valid, every documented coverage gap is in the backlog and every backlog entry is still a
gap, and every generated file is current.

Usage
  rasd chain            # print the map and regenerate
  rasd chain --check    # CI: fail on any gap that must not exist, or on drift
"""
