class Repo:
    def __init__(self):
        self.dets = load_detections()
        self.corrs = load_correlations()
        self.items = [*self.dets, *self.corrs]                   # everything that alerts
        self.by_id = {d.id: d for d in self.items}
        self.red = [t for t in load_tests() if "_yaml_error" not in t]
        self.playbooks = load_docs(DFIR / "playbooks")
        self.scenarios = load_docs(PURPLE / "scenarios")
        actors_path = INTEL / "mappings" / "actors.yml"
        self.actor_doc = yaml.safe_load(actors_path.read_text(encoding="utf-8")) if actors_path.exists() else {}
        self.actors = self.actor_doc.get("actors") or []
        backlog_path = INTEL / "mappings" / "backlog.yml"
        self.backlog_doc = yaml.safe_load(backlog_path.read_text(encoding="utf-8")) if backlog_path.exists() else {}
        self.backlog = self.backlog_doc.get("gaps") or []
        tests, muts = run_tests(None), run_mutations(None)
        fuzz, proof, parity = run_fuzz(None), run_prove(None), run_parity(None)
        self.tests, self.muts, self.fuzz, self.proof, self.parity = tests, muts, fuzz, proof, parity
        self.corr_report = run_correlate(None) if self.corrs else {}
        self.certify_rows = {r["id"]: r for r in run_certify()}
        self.certify = certify_summary(list(self.certify_rows.values()))
        from common import load_jsonl
        self.near = near_misses(load_jsonl(REPLAY_CORPUS)) if REPLAY_CORPUS.exists() else {"detections": {}, "correlations": {}}
        self.scores = {d.id: score_one(d.folder, tests, muts, fuzz, proof, parity) for d in self.dets}
        self.scores.update({c.id: score_correlation(c, self.corr_report.get(c.id, {})) for c in self.corrs})
        self.evidence = {d.id: evidence_front(d.folder) for d in self.items}
        self.public_catalog = load_dataset_catalog()
        self.public = public_summary(self.public_catalog, load_dataset_results() or {})

    # ---- relations -------------------------------------------------------
    def techniques(self) -> list[str]:
        ts = {d.technique for d in self.items}
        return sorted(ts)

    def red_for(self, technique: str) -> list[dict]:
        return [t for t in self.red if (t.get("mitre") or {}).get("technique") == technique]

    def red_for_detection(self, det_id: str) -> list[dict]:
        return [t for t in self.red if det_id in covers(t)]

    def playbooks_for(self, technique: str, det_ids: list[str]) -> list[dict]:
        return [p for p in self.playbooks if technique in (p.get("techniques") or [])
                or set(det_ids) & set(p.get("detections") or [])]

    def scenarios_for(self, technique: str) -> list[dict]:
        return [s for s in self.scenarios if s.get("technique") == technique]

    def actors_for(self, technique: str) -> list[dict]:
        return [a for a in self.actors if any(t.get("id") == technique for t in a.get("techniques") or [])]

    # ---- per detection ---------------------------------------------------
    def det_facts(self, d) -> dict:
        if isinstance(d, Correlation):
            return self.corr_facts(d)
        tp = [r for r in self.tests if r["detection"] == d.id and r["kind"] == "true_positive"]
        tn = [r for r in self.tests if r["detection"] == d.id and r["kind"] == "true_negative"]
        muts = [r for r in self.muts if r["detection"] == d.id]
        par = self.parity.get(d.id, {})
        c = d.contract
        return {
            "tp": len(tp), "tn": len(tn), "tests_pass": all(r["passed"] for r in tp + tn),
            "mutations": len([m for m in muts if m["kind"] == "technique"]),
            "mutations_pass": bool(muts) and all(m["passed"] for m in muts),
            "proof": self.proof.get(d.id, {}).get("score", 0.0),
            "fuzz": self.fuzz.get(d.id, {}).get("resistance", 0.0),
            "fuzz_variants": self.fuzz.get(d.id, {}).get("tried", 0),
            "parity_ok": bool(par) and not par.get("kql") and not par.get("spl") and not par.get("errors")
                         and not par.get("mde"),
            "parity_events": par.get("events", 0),
            "defender_events": par.get("events", 0) if par.get("mde") is not None else None,
            "kql": (ROOT / "queries" / "kql" / f"{d.id}.kql").exists(),
            "spl": (ROOT / "queries" / "spl" / f"{d.id}.spl").exists(),
            "triage": (d.folder / "triage.md").exists(), "response": (d.folder / "response.md").exists(),
            "tuning": (d.folder / "tuning.yml").exists(),
            "engineering": self.scores[d.id]["total"], "operational": self.scores[d.id]["operational_total"],
            "evidence": self.evidence[d.id],
            "depth": (c.get("coverage_depth") or {}).get("level"),
            "blind": len((c.get("detection_logic") or {}).get("blind_spots") or []),
            "events": (c.get("data_contract") or {}).get("required_events") or [],
            "declared": c.get("maturity"),
        }

    def corr_facts(self, c) -> dict:
        """The same facts as det_facts, from what `rasd correlate` proved for this correlation."""
        r = self.corr_report.get(c.id, {})
        b, scen = r.get("base") or {}, r.get("scenarios") or []
        cm, ap, bp = r.get("correlation_mutants") or {}, r.get("aggregation_parity") or {}, r.get("base_parity") or {}
        g = r.get("guarantee") or {}
        mpath = c.folder / "tests" / "mutations.yml"
        technique_mutations = len((yaml.safe_load(mpath.read_text(encoding="utf-8")) or {}).get("mutations") or []) \
            if mpath.exists() else 0
        proven = bool(r) and not correlation_failures(r)
        cc = c.contract
        return {
            "tp": b.get("tp", 0), "tn": b.get("tn", 0),
            "tests_pass": bool(b) and not b.get("failing") and not any(x.get("problem") for x in scen),
            "mutations": technique_mutations,
            "mutations_pass": proven and technique_mutations > 0,
            "proof": min(b.get("proof", 0.0), cm.get("score", 0.0)),
            "fuzz": b.get("fuzz", 0.0), "fuzz_variants": b.get("fuzz_tried", 0),
            "parity_ok": proven and bool(ap.get("comparisons")),
            "parity_events": bp.get("events", 0),
            "kql": (ROOT / query_path(c, "kql")).exists(), "spl": (ROOT / query_path(c, "spl")).exists(),
            "triage": (c.folder / "triage.md").exists(), "response": (c.folder / "response.md").exists(),
            "tuning": (c.folder / "tuning.yml").exists(),
            "engineering": self.scores[c.id]["total"], "operational": self.scores[c.id]["operational_total"],
            "evidence": self.evidence[c.id],
            "depth": (cc.get("coverage_depth") or {}).get("level"),
            "blind": len((cc.get("detection_logic") or {}).get("blind_spots") or []),
            "events": (cc.get("data_contract") or {}).get("required_events") or [],
            "declared": cc.get("maturity"),
            # correlation-only facts
            "scenarios": len(scen), "scenarios_fire": sum(1 for x in scen if x.get("expect") == "fire"),
            "limits": sum(1 for x in scen if x.get("known_limit")),
            "param_mutants": len(cm.get("mutants") or []), "param_survivors": len(cm.get("survivors") or []),
            "base_mutants": b.get("mutants", 0), "base_proof": b.get("proof", 0.0),
            "aggregation_runs": ap.get("comparisons", 0), "aggregation_sequences": ap.get("sequences", 0),
            "aggregation_sets": ap.get("parameter_sets", 0), "guarantee": g.get("burst"),
            "guarantee_alignments": g.get("alignments", 0), "guarantee_spreads": g.get("spreads", 0),
            "describe": r.get("describe", ""),
        }

    def maturity(self, d) -> str:
        f = self.det_facts(d)
        tech = d.technique
        levels = [
            ("draft", True),
            ("tested", f["tp"] >= 4 and f["tn"] >= 4 and f["tests_pass"]),
            ("hardened", f["mutations_pass"] and f["proof"] == 100 and f["fuzz"] == 100 and f["tuning"]),
            ("siem-ready", f["triage"] and f["response"] and f["kql"] and f["spl"] and f["parity_ok"]),
            ("validated", f["evidence"] is not None),
            ("reference", bool(self.red_for_detection(d.id)) and bool(self.playbooks_for(tech, [d.id]))
             and bool(self.actors_for(tech)) and bool(self.scenarios_for(tech)) and f["engineering"] == 100
             and (f["operational"] or 0) >= OPERATIONAL_TARGET),
        ]
        reached = "draft"
        for name, ok in levels:
            if not ok:
                break
            reached = name
        return reached

    # ---- per technique: the 20-point map -----------------------------------
    def checklist(self, technique: str) -> dict[str, str]:
        dets = [d for d in self.items if d.technique == technique]
        facts = [self.det_facts(d) for d in dets]
        reds = self.red_for(technique)
        allf = lambda key: bool(facts) and all(f[key] for f in facts)
        state = {
            "Red emulation": bool(reds),
            "Expected telemetry": bool(reds) and all(t.get("telemetry") for t in reds),
            "Detection rule": bool(dets),
            "SPL query": allf("spl"), "KQL query": allf("kql"),
            "TP tests": bool(facts) and all(f["tp"] >= 4 and f["tests_pass"] for f in facts),
            "TN tests": bool(facts) and all(f["tn"] >= 4 and f["tests_pass"] for f in facts),
            "Mutation tests": allf("mutations_pass"),
            "Triage guide": allf("triage"), "Response guide": allf("response"),
            "DFIR playbook": bool(self.playbooks_for(technique, [d.id for d in dets])),
            "CTI mapping": bool(self.actors_for(technique)),
            "Purple scenario": bool(self.scenarios_for(technique)),
            "Cleanup steps": bool(reds) and all((t.get("scripts") or {}).get("cleanup") and (t.get("cleanup") or {}).get("verify")
                                                for t in reds),
            "Evidence file": allf("evidence"),
            "Engineering Score": bool(facts) and all(f["engineering"] == 100 for f in facts),
            "Operational Score": bool(facts) and all((f["operational"] or 0) >= OPERATIONAL_TARGET for f in facts),
            "Coverage depth": allf("depth"),
            "Known blind spots": bool(facts) and all(f["blind"] >= 2 for f in facts),
            "Data source requirements": allf("events"),
        }
        return {k: ("done" if v else ("pending" if k in PENDING_ITEMS else "missing")) for k, v in state.items()}


