def gate_errors(repo: Repo) -> list[str]:
    errs = []
    for d in repo.items:
        declared, computed = d.contract.get("maturity"), repo.maturity(d)
        if declared in MATURITY and MATURITY.index(declared) > MATURITY.index(computed):
            errs.append(f"{d.id}: contract declares maturity '{declared}' but the repository proves '{computed}'")
    for t in repo.techniques():
        for item, st in repo.checklist(t).items():
            if st == "missing":
                errs.append(f"{t}: chain item '{item}' is missing")
    for p in repo.playbooks:
        name = p["_path"].name
        text = p["_text"]
        for section in ("## Trigger", "## Required Data", "## First 15 Minutes", "## Deep Investigation",
                        "## Evidence to Collect", "## Escalate If", "## Closure Guidance"):
            if section not in text:
                errs.append(f"dfir/playbooks/{name}: missing section '{section}'")
        if "| Evidence | Source | Purpose |" not in text:
            errs.append(f"dfir/playbooks/{name}: Evidence to Collect needs the table | Evidence | Source | Purpose |")
        for d in p.get("detections") or []:
            if d not in repo.by_id:
                errs.append(f"dfir/playbooks/{name}: unknown detection '{d}'")
        for r in p.get("red_tests") or []:
            if r not in {t["id"] for t in repo.red}:
                errs.append(f"dfir/playbooks/{name}: unknown red test '{r}'")
        for t in p.get("techniques") or []:
            if not re.fullmatch(r"T\d{4}(\.\d{3})?", str(t)):
                errs.append(f"dfir/playbooks/{name}: invalid technique '{t}'")
    for s in repo.scenarios:
        name = s["_path"].name
        if not s.get("detections"):
            errs.append(f"purple/scenarios/{name}: no detection link")
        for d in s.get("detections") or []:
            if d not in repo.by_id:
                errs.append(f"purple/scenarios/{name}: unknown detection '{d}'")
        if s.get("red_test") not in {t["id"] for t in repo.red}:
            errs.append(f"purple/scenarios/{name}: unknown red test '{s.get('red_test')}'")
        if not (DFIR / "playbooks" / f"{s.get('dfir_playbook')}.md").exists():
            errs.append(f"purple/scenarios/{name}: unknown DFIR playbook '{s.get('dfir_playbook')}'")
    for t in repo.red:
        pb = t.get("dfir_playbook")
        if not pb or not (ROOT / pb).exists():
            errs.append(f"red/{t['platform']}/{t['id']}: dfir_playbook missing or not found ({pb})")
        sc = t.get("purple_scenario")
        if sc and not (ROOT / sc).exists():
            errs.append(f"red/{t['platform']}/{t['id']}: purple_scenario not found ({sc})")
    errs += backlog_errors(repo)
    errs += attack_alias_errors(repo)
    known = set(repo.techniques()) | {(t.get("mitre") or {}).get("technique") for t in repo.red}
    for a in repo.actors:
        if not re.fullmatch(r"G\d{4}", str(a.get("id", ""))) or not str(a.get("source", "")).startswith("https://attack.mitre.org/groups/"):
            errs.append(f"intel/mappings/actors.yml: {a.get('group')}: needs a Gxxxx id and its attack.mitre.org source")
        for t in a.get("techniques") or []:
            if t.get("id") not in known:
                errs.append(f"intel/mappings/actors.yml: {a.get('group')}: technique {t.get('id')} is not detected or emulated by RASD")
    return errs


def backlog_errors(repo: Repo) -> list[str]:
    """Every documented gap is in the backlog, and every backlog entry is still a gap."""
    errs = []
    where = "intel/mappings/backlog.yml"
    tests = {t["id"]: t for t in repo.red}
    listed = {g.get("red_test") for g in repo.backlog}
    for t in repo.red:
        if t.get("gap") and t.get("category") != "posture" and t["id"] not in listed:
            errs.append(f"{where}: red test {t['id']} documents a coverage gap but has no backlog entry")
    for g in repo.backlog:
        tech, test = g.get("technique"), tests.get(g.get("red_test"))
        if test is None:
            errs.append(f"{where}: {tech}: red test '{g.get('red_test')}' not found")
        elif (test.get("mitre") or {}).get("technique") != tech:
            errs.append(f"{where}: {tech}: red test {test['id']} maps {(test.get('mitre') or {}).get('technique')}")
        if tech in repo.techniques():
            errs.append(f"{where}: {tech} is covered by a detection now: drop it here and move the idea to "
                        "the Built table in intel/mappings/detection_ideas.md")
        flags = ("log_source_mapped", "red_test_produces")
        if not all(isinstance(g.get(k), bool) for k in flags) or not all(
                g.get(k) for k in ("name", "telemetry", "missing", "next", "validation")):
            errs.append(f"{where}: {tech}: needs name, log_source_mapped and red_test_produces (true/false), "
                        "telemetry, missing, next, validation")
        elif g["red_test_produces"] and not g["log_source_mapped"]:
            errs.append(f"{where}: {tech}: a red test cannot produce telemetry RASD does not map")
    return errs


def attack_alias_errors(repo: Repo) -> list[str]:
    """Primary mappings follow ATT&CK v19.2 and the v18 aliases stay consistent: every alias names an
    existing detection, no legacy ID is still a folder name or a rule's own tag, no rule carries the
    v18-only defense-evasion tactic, and every red test maps a current technique."""
    where = "intel/mappings/attack_v18_aliases.yml"
    aliases = attack_aliases()
    old_techs = set(aliases["techniques"].values())
    errs = [f"{where}: {d} is not a detection" for d in aliases["detections"] if d not in repo.by_id]
    errs += [f"{where}: legacy id {legacy} is still a detection folder" for legacy in aliases["detections"].values()
             if legacy in repo.by_id]
    errs += [f"{where}: {new} is not named in TECHNIQUE_NAMES" for new in aliases["techniques"] if new not in TECHNIQUE_NAMES]
    doc = yaml.safe_load(ATTACK_ALIASES.read_text(encoding="utf-8")) if ATTACK_ALIASES.exists() else {}
    if aliases["techniques"] and aliases["attack_version"] != ATTACK_VERSION:
        errs.append(f"{where}: attack_version {aliases['attack_version']} is not the ATT&CK version the tools use "
                    f"({ATTACK_VERSION}, tools/common.py)")
    for t in doc.get("techniques") or []:
        new_id, name = str(t.get("new_technique")), t.get("new_name")
        if new_id in TECHNIQUE_NAMES and name != TECHNIQUE_NAMES[new_id]:
            errs.append(f"{where}: {new_id} is named \"{name}\" here and \"{TECHNIQUE_NAMES[new_id]}\" in tools/common.py")
        if t.get("new_tactic") not in ATTACK_TACTICS:
            errs.append(f"{where}: {new_id}: new_tactic {t.get('new_tactic')} is not an ATT&CK v{ATTACK_VERSION} tactic")
    for t in doc.get("tactics") or []:
        if t.get("old_tactic") in ATTACK_TACTICS:
            errs.append(f"{where}: old_tactic {t.get('old_tactic')} is still a tactic in tools/common.py")
        errs += [f"{where}: {x} is not an ATT&CK v{ATTACK_VERSION} tactic" for x in t.get("new_tactics") or []
                 if x not in ATTACK_TACTICS]
    for d in repo.items:
        rule = d.rule if not isinstance(d, Correlation) else d.base
        tags = [str(t) for t in (d.rule.get("tags") or []) + (rule.get("tags") or [])]
        for tag in tags:
            tech = tag.split(".", 1)[1].upper() if re.match(r"^attack\.t\d{4}", tag) else None
            if tech in old_techs:
                errs.append(f"{d.id}: tag {tag} is the ATT&CK v18 ID; tag the v19.2 technique ({where} keeps the alias)")
            if tag == "attack.defense-evasion":
                errs.append(f"{d.id}: attack.defense-evasion is the v18 tactic; ATT&CK v19 tags it attack.stealth or "
                            "attack.defense-impairment")
        if d.technique in old_techs:
            errs.append(f"{d.id}: named after the ATT&CK v18 technique {d.technique}")
    errs += [f"red/{t['platform']}/{t['id']}: maps the ATT&CK v18 technique {(t.get('mitre') or {}).get('technique')}"
             for t in repo.red if (t.get("mitre") or {}).get("technique") in old_techs]
    return errs


BACKLOG_TIERS = ("can be validated in the lab today", "needs a red test step", "needs a new log source")


def backlog_tier(g: dict) -> int:
    return 0 if g.get("red_test_produces") else (1 if g.get("log_source_mapped") else 2)


def backlog_ranked(repo: Repo) -> list[tuple[dict, list[dict]]]:
    """Gaps whose rule can be written and validated in the lab today first, then those that need only a red
    test step, then those that need a new log source; ties go to the number of tracked groups with a
    documented procedure for the technique."""
    rows = [(g, repo.actors_for(g["technique"])) for g in repo.backlog]
    return sorted(rows, key=lambda r: (backlog_tier(r[0]), -len(r[1]), r[0]["technique"]))


