    out = HEADER + "# Data Source Coverage\n\nWhich telemetry each detection depends on, and what goes blind without it. Generated from the rules' log sources and event IDs; investigation-only sources come from the offensive tests' expected telemetry.\n\n"
    out += "## Detection data sources\n\n| Data Source | Used By | Criticality | Risk if Missing |\n|---|---|---|---|\n"
    for src in sorted(users, key=lambda s: (-len(users[s]), s)):
        ds = users[src]
        crit = "Critical" if len(ds) >= 3 else ("High" if any(d.level in ("high", "critical") for d in ds) else "Medium")
        names = ", ".join(f"[{d.id}](../{det_path(d)}/)" for d in ds)
        out += f"| {src} | {names} | {crit} | {len(ds)} detection(s) go blind |\n"
    extra: dict[str, set] = defaultdict(set)
    for t in repo.red:
        for tel in t.get("telemetry") or []:
            if not tel.get("used_by"):
                extra[f"{md_text(tel['source'])} · {md_text(tel['event'])}"].add(t["id"])
    out += ("\n## Investigation and hunting data sources\n\nNot used by a rule today, but the DFIR playbooks and the "
            "offensive tests rely on them.\n\n| Data Source | Red tests that produce it | Risk if Missing |\n|---|---|---|\n")
    for src in sorted(extra):
        tests = ", ".join(sorted(extra[src]))
        out += f"| {src} | {tests} | Investigation and hunting lose this view |\n"
    return out + FOOTER


