def badge(label: str, message: str, colour: str) -> str:
    """A static shields.io badge. The values come from this build and CI fails when they are stale,
    so the badge cannot claim more than the repository proves."""
    esc = lambda text: quote(text.replace("-", "--").replace("_", "__"), safe="")
    return f"![{label}: {message}](https://img.shields.io/badge/{esc(label)}-{esc(message)}-{colour})"


def proven(repo: Repo, level: str) -> list:
    """The detections at or above a maturity level."""
    return [d for d in repo.items if MATURITY.index(repo.maturity(d)) >= MATURITY.index(level)]


def ops_average(repo: Repo, validated: list) -> float | None:
    ops = [repo.scores[d.id]["operational_total"] or 0 for d in validated]
    return sum(ops) / len(ops) if ops else None


def status_line(repo: Repo, docs: str = "docs/") -> str:
    """One honest sentence on how far the detections are proven; `docs` is the path to docs/ from the page."""
    n = len(repo.items)
    validated = [d for d in repo.items if repo.evidence[d.id]]
    plan = f"[evidence plan]({docs}EVIDENCE_PLAN.md)"
    pc = public_counts(repo)
    pub = pc["validated"]
    public = f"[public data]({docs}PUBLIC_DATA_VALIDATION.md)"
    held = (f", meeting {pc['holdout_met']} of {pc['holdout_expected']} expectations in {pc['holdout_files_expecting']} of "
            f"{pc['holdout_files']} held-out files" if pc["holdout_expected"] else "")
    if not validated:
        return (f"**Status:** SIEM-Ready, not yet Validated: {len(proven(repo, 'siem-ready'))} of {n} detections "
                f"are SIEM-Ready and {pub} fire on public attack datasets{held} ({public}); none has lab evidence yet ({plan}).")
    if len(validated) < n:
        return (f"**Status:** {len(validated)} of {n} detections Validated (lab evidence); the other {n - len(validated)} "
                f"wait for a lab run ({plan}).")
    return (f"**Status:** all {n} detections Validated (lab evidence). Production use still needs tuning to your environment "
            f"([adoption guide]({docs}ENTERPRISE_ADOPTION.md)).")


def render_status(repo: Repo) -> str:
    n = len(repo.items)
    validated = [d for d in repo.items if repo.evidence[d.id]]
    eng = sum(s["total"] for s in repo.scores.values()) / len(repo.scores)
    ops = ops_average(repo, validated)
    all_ok = len(validated) == n and all((repo.scores[d.id]["operational_total"] or 0) >= OPERATIONAL_TARGET
                                         for d in validated)
    badges = [
        badge("detections", str(n), CALM["info"]),
        badge("engineering", f"{eng:.0f}/100", CALM["good"] if eng == 100 else CALM["wait"]),
        badge("operational", f"{ops:.0f}/100" if ops is not None else "pending", CALM["good"] if all_ok else CALM["wait"]),
        badge("public data", f"{public_counts(repo)['validated']}/{n}", CALM["info"]),
        badge("validated", f"{len(validated)}/{n}", CALM["good"] if len(validated) == n else CALM["none"]),
    ]
    return STATUS_START + "\n" + "\n".join(badges) + "\n\n" + status_line(repo) + "\n" + STATUS_END


