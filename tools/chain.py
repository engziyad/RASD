def defender_summary(repo: Repo) -> str:
    """Parity of the optional Defender XDR advanced hunting queries, when any rule has one."""
    rows = [r for r in repo.parity.values() if r.get("mde") is not None]
    if not rows:
        return ""
    bad = sum(len(r["mde"]) for r in rows)
    return (f" · Defender advanced hunting: {len(rows)} rules on {sum(r['events'] for r in rows)} events, each in both "
            f"FolderPath forms ({bad} divergences)")


